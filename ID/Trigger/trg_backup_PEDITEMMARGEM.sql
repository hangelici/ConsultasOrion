create or replace TRIGGER trg_backup_PEDITEMMARGEM
AFTER INSERT ON VIASOFT.PEDITEMMARGEM
FOR EACH ROW
BEGIN
    INSERT INTO VIASOFT.PEDITEMMARGEM_BACKUP (
        IDPEDITEMMARGEM, ESTAB, SERIE, NUMERO, SEQPEDITE, 
        CUSTOGERENCIAL, MARGEMMINITEM, MARGEMPRATITEM, MARGEMMINGRUPO, 
        MARGEMPRATGRUPO, MARGEMMINMARCA, MARGEMPRATMARCA, 
        MARGEMMINPEDIDO, MARGEMPRATPEDIDO, MARGEMMINREPRES, 
        MARGEMPRATREPRES, CUSTOGERENCIALORI, 
        MARGEMPRATPEDIDOANT, MARGEMPRATREPRESANT
    ) VALUES (
        :NEW.IDPEDITEMMARGEM, :NEW.ESTAB, :NEW.SERIE, :NEW.NUMERO, :NEW.SEQPEDITE, 
        :NEW.CUSTOGERENCIAL, :NEW.MARGEMMINITEM, :NEW.MARGEMPRATITEM, :NEW.MARGEMMINGRUPO, 
        :NEW.MARGEMPRATGRUPO, :NEW.MARGEMMINMARCA, :NEW.MARGEMPRATMARCA, 
        :NEW.MARGEMMINPEDIDO, :NEW.MARGEMPRATPEDIDO, :NEW.MARGEMMINREPRES, 
        :NEW.MARGEMPRATREPRES, :NEW.CUSTOGERENCIALORI, 
        :NEW.MARGEMPRATPEDIDOANT, :NEW.MARGEMPRATREPRESANT
    );
END;
