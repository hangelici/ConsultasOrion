         AND DADOS.TIPO_PROD = 'N'
         AND DADOS.DESCRICAO LIKE 'ALX%'
        THEN 'E'

        WHEN DADOS.CHAVCHAVENF IS NULL
         AND DADOS.TIPO_PROD = 'P'
         AND DADOS.DESCRICAO LIKE 'AT%'
        THEN 'E'

        WHEN DADOS.CHAVCHAVENF IS NULL
         AND DADOS.TIPO_PROD = 'P'
         AND DADOS.DESCRICAO LIKE 'TRANSP%'
        THEN 'E'

        WHEN DADOS.CHAVCHAVENF IS NULL
         AND DADOS.TIPO_PROD = 'P'
         AND DADOS.DESCRICAO LIKE 'FAT%'
        THEN 'FAT'

