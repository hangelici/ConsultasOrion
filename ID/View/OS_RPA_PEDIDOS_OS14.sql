            INNER JOIN (
                SELECT
                    ESTAB,
                    SERIE,
                    NUMERO,
                    MAX(IDNOTIFICA) AS NOTIFICA
                FROM NOTIFICAESTRATEGIA
                GROUP BY ESTAB, SERIE, NUMERO
            ) MAXIMO
