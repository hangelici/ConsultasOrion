SELECT DADOS.CODI_REV,
       DADOS.ANO_VEN,
       DADOS.MES_VEN,
       DADOS.OPER_VEN,
       DADOS.CFOP_VEN,
       DADOS.DESC_OPR,
       DADOS.NCMP_PRO,
       DADOS.SINA_OPR,
       SUM(DADOS.VALF_VEN) AS VALF_VEN,
       SUM(DADOS.VOLF_VEN) AS VOLF_VEN,
       SUM(DADOS.VOLU_VEN) AS VOLU_VEN,
       SUM(DADOS.VOLR_VEN) AS VOLR_VEN
FROM(
SELECT 
CAST(NFCAB.ESTAB AS VARCHAR(20)) AS CODI_REV,
EXTRACT(MONTH FROM NFCAB.DTEMISSAO) AS MES_VEN,
EXTRACT(YEAR FROM NFCAB.DTEMISSAO) AS ANO_VEN,
CAST(COPY(CFOP_ITEM.CFOP, 0,20) AS VARCHAR(20)) AS OPER_VEN,
CAST(COPY(CFOP_ITEM.CFOP, 0,4) AS VARCHAR(4)) AS CFOP_VEN,
CAST(COPY(CFOP_ITEM.NOME, 0, 60) AS VARCHAR(60)) AS DESC_OPR,
CAST(COPY(PCLASFIS.NCM, 0, 8) AS VARCHAR(8)) AS NCMP_PRO,
CAST(NFCFG.ENTRADASAIDA AS VARCHAR(1)) AS SINA_OPR,
CASE WHEN FILIAL.ESTAB IS NOT NULL THEN CAST(NFITEM.VALORTOTAL + NVLF0(NFITEM.DESCTOTAL)AS NUMERIC(18,4)) ELSE 0 END VALF_VEN,
CASE WHEN FILIAL.ESTAB IS NOT NULL then CAST(NFITEM.QUANTIDADE * ITEMAGRO.PESOLIQUIDO AS NUMERIC(18,3)) else 0 end VOLF_VEN,
CAST(NFITEM.VALORTOTAL + NVLF0(NFITEM.DESCTOTAL)AS NUMERIC(18,4)) AS VOLU_VEN,
CAST(NFITEM.QUANTIDADE * ITEMAGRO.PESOLIQUIDO AS NUMERIC(18,3)) AS VOLR_VEN

FROM ITEMAGRO
INNER JOIN NFITEM ON NFITEM.ITEM = ITEMAGRO.ITEM
INNER JOIN NFCAB ON 
    NFITEM.ESTAB = NFCAB.ESTAB
    AND NFITEM.SEQNOTA = NFCAB.SEQNOTA
LEFT JOIN CFOP CFOP_ITEM ON CFOP_ITEM.CFOP = NFITEM.CFOP
INNER JOIN NFCFG ON NFCFG.NOTACONF = NFCAB.NOTACONF
INNER JOIN CONTAMOV CLIENTE ON CLIENTE.NUMEROCM = NFCAB.NUMEROCM
INNER JOIN PCLASFIS ON PCLASFIS.CLASFISCAL = ITEMAGRO.CLASFISCAL
LEFT JOIN FILIAL ON FILIAL.CNPJ= CLIENTE.CNPJF

WHERE ITEMAGRO.MARCA IN (210)
AND NFCFG.FISCAL='S'
AND NFCAB.DTEMISSAO >= '01/04/2026'
    
)DADOS

GROUP BY DADOS.CODI_REV,
         DADOS.MES_VEN,
         DADOS.ANO_VEN,
         DADOS.OPER_VEN,
         DADOS.CFOP_VEN,
         DADOS.DESC_OPR,
         DADOS.NCMP_PRO,
         DADOS.SINA_OPR