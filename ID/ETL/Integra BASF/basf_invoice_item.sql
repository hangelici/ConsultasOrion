WITH BASE AS (
   SELECT /*+ MATERIALIZE */
   NFCAB.ESTAB,
   NFCAB.SEQNOTA,
   NFITEM.SEQNOTAITEM,
   NFCAB.NOTA,
   NFCAB.NOTACONF,
   NFCAB.NUMEROCM,
   NFCAB.SEQENDERECO,
   NFCAB.SERIE,
   NFCAB.CHAVEACESSONFE,
   NFCAB.DTEMISSAO,
   NFCAB.PRAZOPAGTO,
   ITEMAGRO.DESCRICAO AS DESC_PRO,
   ITEMAGRO.ITEM AS CODI_PRO,
   ITEMAGRO.UNIDADE AS UNID_PRO,
   ITEMAGRO.NROCODBAR,
   NFITEM.CFOP,
   ITEMAGRO.NCM,
   NFITEM.ITEM,
   NFCAB.STATUS,
   NFITEM.CULTURAID,
   NFITEM.QUANTIDADE,
   NFITEM.VLRTOTALINDEX,
   NFITEM.VALORTOTAL,
   NFITEM.DESCTOTAL,
   NFCFG.ENTRADASAIDA
   FROM NFCAB
   INNER JOIN NFITEM ON
      NFITEM.ESTAB = NFCAB.ESTAB
      AND NFITEM.SEQNOTA = NFCAB.SEQNOTA
   INNER JOIN ITEMAGRO ON ITEMAGRO.ITEM = NFITEM.ITEM
   INNER JOIN NFCFG ON NFCFG.NOTACONF = NFCAB.NOTACONF
   WHERE NFCAB.STATUS <> 'C'
   AND ITEMAGRO.MARCA = 210
   AND NFCAB.DTEMISSAO BETWEEN '01/04/2026' AND CURRENT_DATE
),
APARTIR AS (
   SELECT /*+ LEADING(BASE NFI NF NFCFG) USE_NL(NFI) USE_NL(NF) INDEX(NFI IDX_FK_NFITEM_NFITEMAPARTIRDE) */
   NFI.ESTAB, NFI.SEQNOTA, NFI.SEQNOTAITEM,
   BASE.ENTRADASAIDA,
   NFCFG.ENTRADASAIDA AS ENTSAID_ORI,
   MIN(NF.NOTA) AS NOTA_ORI
   FROM NFITEMAPARTIRDE NFI
   --- NOTAS DE DEVOLUÇÃO 
   INNER JOIN BASE ON
      BASE.ESTAB = NFI.ESTAB
      AND BASE.SEQNOTA = NFI.SEQNOTA
      AND BASE.SEQNOTAITEM = NFI.SEQNOTAITEM
   --- NOTAS DE ORIGEM
   INNER JOIN NFCAB NF ON
      NF.ESTAB = NFI.ESTABORIGEM
      AND NF.SEQNOTA = NFI.SEQNOTAORIGEM
   INNER JOIN NFCFG ON NFCFG.NOTACONF = NF.NOTACONF
   WHERE
   --- DEVOLUÇÃO DO CLIENTE DE VENDA NOSSA
   (BASE.ENTRADASAIDA = 'E' AND NFCFG.ENTRADASAIDA = 'S')
   OR
   --- COMPRA NOSSA E DEVOLUÇÃO NOSSA TB
   (BASE.ENTRADASAIDA = 'S' AND NFCFG.ENTRADASAIDA = 'E')
   GROUP BY NFI.ESTAB, NFI.SEQNOTA, NFI.SEQNOTAITEM,BASE.ENTRADASAIDA,NFCFG.ENTRADASAIDA
),
IMPOSTO AS (
   --- impostos somados por item da nota
   SELECT /*+ LEADING(B I) USE_NL(I) */
   I.ESTAB, I.SEQNOTA, I.SEQNOTAITEM,
   SUM(I.VALORIMPOSTO) AS VALORIMPOSTO
   FROM BASE B
   INNER JOIN NFITEMIMPOSTO I ON
      I.ESTAB = B.ESTAB
      AND I.SEQNOTA = B.SEQNOTA
      AND I.SEQNOTAITEM = B.SEQNOTAITEM
   GROUP BY I.ESTAB, I.SEQNOTA, I.SEQNOTAITEM
)
SELECT
CAST(COPY(BASE.NOTA, 0,20) AS VARCHAR(20)) AS CODI_VEN,      
CAST(COPY(BASE.ESTAB, 0,20) AS VARCHAR(20)) AS CODI_REV,
CAST(COPY(210, 0,20) AS VARCHAR(20)) AS CODI_FAB,
CAST(COPY(BASE.NOTA, 0,20) AS VARCHAR(20)) AS NUME_VEN,
CAST(BASE.SEQNOTAITEM AS VARCHAR2(20)) AS NUME_ITE,
CAST(COPY(BASE.SERIE, 0,20) AS VARCHAR(20)) AS SERI_VEN,
APARTIR.NOTA_ORI AS NREF_VEN,
BASE.CHAVEACESSONFE AS CHAV_VEN,
NFCFG.FINNFE AS FINA_VEN,
null as NUME_PED,
RPAD(TO_CHAR(BASE.DTEMISSAO,'YYYY/MM/DD'),19,' 00:00:00') AS DATA_VEN,
RPAD(TO_CHAR(BASE.PRAZOPAGTO,'YYYY/MM/DD'),19,' 00:00:00') AS DATV_VEN,
CAST(null AS VARCHAR(20)) AS CODI_CON,
CAST(null AS VARCHAR(60)) AS DESC_CON,
CAST(null AS VARCHAR(1)) AS TIPO_CON,
CAST(NULL AS VARCHAR(60)) AS PRAZ_CON,
CAST(COPY(CFOP_ITEM.CFOP, 0,20) AS VARCHAR(20)) AS OPER_VEN,
CAST(COPY(CFOP_ITEM.NOME, 0, 60) AS VARCHAR(60)) AS DESC_OPR,
CAST(COPY(CFOP_ITEM.MOVIMENTO, 0, 1) AS VARCHAR(1)) AS SINA_OPR,
BASE.CFOP AS CFOP_VEN,
CASE WHEN (BASE.STATUS = 'N') THEN  'A'  ELSE    'C' END AS STAT_VEN,
CASE WHEN CONTAMOV_U.PROGRAMA_BASF = 'S' THEN COALESCE(CLIENTE.CNPJF,CONTAMOV.cnpjf) ELSE 'LGPD' END AS DEST_VEN,
CASE 
      WHEN BASE.SEQENDERECO IS NULL THEN CAST(COPY(CONTAMOV.NUMEROCM, 0,20) AS VARCHAR(20))||' - '||SUBSTR(CONTAMOV.cnpjf,length(CONTAMOV.cnpjf)-1,2)||' - 0'
   ELSE CAST(COPY(CLIENTE.NUMEROCM, 0,20) AS VARCHAR(20))||' - '||SUBSTR(CLIENTE.cnpjf,length(CLIENTE.cnpjf)-1,2)||' - '||CLIENTE.seqendereco 
END CODI_CLI,
CAST((UF.CODIGO * 100000) + (CIDADE.IBGE) AS VARCHAR(7)) AS MUNI_CLI,
CAST(BASE.ITEM AS VARCHAR(20)) AS CODI_PRO,
BASE.DESC_PRO,
BASE.UNID_PRO,
BASE.NCM AS NCMP_PRO,
CAST(BASE.NROCODBAR AS VARCHAR(14)) AS BARR_PRO,
CAST(NULL AS VARCHAR(20)) AS LOTE_IVN,
IMPOSTO.VALORIMPOSTO AS TRIB_IVN,
CAST(COPY(CULTURA.CULTURAID, 0,20) AS VARCHAR(20)) AS CODI_CUL,
CAST(COPY(CULTURA.NOME, 0,20) AS VARCHAR(20)) AS DESC_CUL,
CAST(BASE.VALORTOTAL + NVLF0(BASE.DESCTOTAL)AS NUMERIC(18,4)) AS PBRU_IVN,
CAST(BASE.VALORTOTAL AS NUMERIC(18,4))AS PLIQ_IVN,
COALESCE(CAST(BASE.VLRTOTALINDEX AS NUMERIC(18,4)),0) AS PBAR_IVN,
CAST(BASE.QUANTIDADE AS NUMERIC(18,3)) AS QTDE_IVN

FROM BASE 

LEFT JOIN CFOP CFOP_ITEM
ON (CFOP_ITEM.CFOP = BASE.CFOP)

INNER JOIN NFCFG
ON (NFCFG.NOTACONF = BASE.NOTACONF)

LEFT JOIN CULTURA
ON (CULTURA.CULTURAID = BASE.CULTURAID)

LEFT JOIN IMPOSTO
ON (IMPOSTO.ESTAB = BASE.ESTAB)
AND (IMPOSTO.SEQNOTA = BASE.SEQNOTA)
AND (IMPOSTO.SEQNOTAITEM = BASE.SEQNOTAITEM)

LEFT JOIN ENDERECO CLIENTE ON CLIENTE.NUMEROCM = BASE.NUMEROCM
AND CLIENTE.SEQENDERECO = BASE.SEQENDERECO

LEFT JOIN CONTAMOV ON CONTAMOV.NUMEROCM = BASE.NUMEROCM
INNER JOIN CONTAMOV_U ON CONTAMOV_U.NUMEROCM = CONTAMOV.NUMEROCM

INNER JOIN FILIAL ON FILIAL.ESTAB = BASE.ESTAB
INNER JOIN CIDADE ON CIDADE.CIDADE = FILIAL.CIDADE
INNER JOIN UF ON UF.UF = CIDADE.UF

LEFT JOIN APARTIR ON
   APARTIR.ESTAB = BASE.ESTAB
   AND APARTIR.SEQNOTA = BASE.SEQNOTA
   AND APARTIR.SEQNOTAITEM = BASE.SEQNOTAITEM