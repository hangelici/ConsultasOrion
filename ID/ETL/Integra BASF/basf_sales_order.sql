SELECT
CAST(PEDCAB.NUMERO AS VARCHAR(20)) AS CODI_PED,
CAST(PEDCAB.ESTAB AS VARCHAR(20)) AS CODI_REV,
CAST(ITEMAGRO.MARCA AS VARCHAR(20)) AS CODI_FAB,
CAST(PEDCAB.NUMERO AS VARCHAR(20)) AS NUME_PED,
CAST(PEDCAB.SERIE AS VARCHAR(20)) AS SERI_PED,
PEDCAB.DTEMISSAO AS DATA_PED,
PEDCAB.DTVALIDADE AS DATV_PED,
NVL(PEDITEM.DTENTREGA,PEDCAB.DTPREVISAO) AS DATP_PED,
CASE WHEN PEDCAB.STATUS <> 'C' THEN 'A' ELSE 'C' END STAT_PED,
CASE 
    WHEN NVL(PEDCAB.SEQENDERECO,0) = 0 THEN CAST(COPY(CONTAMOV.NUMEROCM, 0,20) AS VARCHAR(20))||' - '||SUBSTR(CONTAMOV.CNPJF,LENGTH(CONTAMOV.CNPJF)-1,2)||' - 0'
    ELSE 
    CAST(COPY(ENDERECO.NUMEROCM, 0,20) AS VARCHAR(20))||' - '||SUBSTR(ENDERECO.CNPJF,LENGTH(ENDERECO.CNPJF)-1,2)||' - '||ENDERECO.SEQENDERECO 
END CODI_CLI,
UF.CODIGO||''||CIDADE.IBGE AS muni_ped,
CAST(peditem.ITEM AS VARCHAR(20)) codi_pro,
cast(itemagro.descricao as varchar2(60)) as desc_pro,
itemagro.ncm as ncmp_pro,
itemagro.unidade as unid_pro,
null as barr_pro,
null as cind_pro,
null as lote_ivn,
SUM(PEDITEMIMPOSTO.VALORIMPOSTO) as trib_ivn,
peditem.CULTURAID as codi_cul,
CULTURA.NOME AS desc_cul,
peditem.valor - nvl(peditem.desconto,0) as pliq_ped,
peditem.valor as pbru_ped,
peditem.quantidade as qtde_ped
FROM PEDCAB
INNER JOIN FILIAL ON FILIAL.ESTAB = PEDCAB.ESTAB
INNER JOIN CIDADE ON CIDADE.CIDADE = FILIAL.CIDADE
INNER JOIN PEDITEM ON
    PEDITEM.ESTAB = PEDCAB.ESTAB
    AND PEDITEM.SERIE = PEDCAB.SERIE
    AND PEDITEM.NUMERO = PEDCAB.NUMERO
LEFT JOIN PEDCAB_U ON
    PEDCAB_U.ESTAB = PEDCAB.ESTAB
    AND PEDCAB_U.SERIE = PEDCAB.SERIE
    AND PEDCAB_U.NUMERO = PEDCAB.NUMERO
INNER JOIN ITEMAGRO ON ITEMAGRO.ITEM = PEDITEM.ITEM
INNER JOIN CONTAMOV ON CONTAMOV.NUMEROCM = PEDCAB.PESSOA
LEFT JOIN ENDERECO ON
    ENDERECO.NUMEROCM = PEDCAB.PESSOA
    AND ENDERECO.SEQENDERECO = PEDCAB.SEQENDERECO
LEFT JOIN CIDADE ON CIDADE.CIDADE = NVL(ENDERECO.CIDADE,CONTAMOV.CIDADE)
LEFT JOIN UF ON UF.UF = CIDADE.UF
LEFT JOIN CULTURA ON CULTURA.CULTURAID = peditem.CULTURAID
LEFT JOIN PEDITEMIMPOSTO ON
    PEDITEMIMPOSTO.ESTAB = PEDITEM.ESTAB
    AND PEDITEMIMPOSTO.SERIE = PEDITEM.SERIE
    AND PEDITEMIMPOSTO.NUMERO = PEDITEM.NUMERO
    AND PEDITEMIMPOSTO.SEQPEDITE = PEDITEM.SEQPEDITE
WHERE
ITEMAGRO.MARCA IN (210)
AND CIDADE.UF IN ('SP')
AND PEDCAB.DTEMISSAO BETWEEN '01/04/2026' AND CURRENT_DATE

GROUP BY
PEDCAB.NUMERO,
PEDCAB.ESTAB ,
ITEMAGRO.MARCA,
PEDCAB.NUMERO,
PEDCAB.SERIE ,
PEDCAB.DTEMISSAO,
PEDCAB.DTVALIDADE,
PEDITEM.DTENTREGA,
PEDCAB.DTPREVISAO,
PEDCAB.STATUS,
PEDCAB.SEQENDERECO,
CONTAMOV.NUMEROCM,
CONTAMOV.CNPJF,
ENDERECO.NUMEROCM,
ENDERECO.CNPJF,
ENDERECO.SEQENDERECO,
UF.CODIGO,
CIDADE.IBGE,
peditem.ITEM ,
itemagro.descricao,
itemagro.ncm,
itemagro.unidade,
peditem.CULTURAID ,
CULTURA.NOME,
peditem.desconto,
peditem.valor,
peditem.quantidade