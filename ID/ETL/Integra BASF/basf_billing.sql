SELECT DADOS.CODI_REV,
       DADOS.MES_VEN,
       DADOS.ANO_VEN,
       DADOS.OPER_VEN,
       DADOS.CFOP_VEN,
       DADOS.DESC_VEN,
       DADOS.SINA_VEN,
       SUM(DADOS.VOLU_VEN) AS VOLU_VEN,
       SUM(DADOS.VDEF_VEN) AS VDEF_VEN,
       SUM(DADOS.VIND_VEN) AS VIND_VEN
FROM(
SELECT DISTINCT CAST(NFCAB.ESTAB AS VARCHAR2(20)) AS CODI_REV,
   EXTRACT(MONTH FROM NFCAB.DTEMISSAO) AS MES_VEN,
   EXTRACT(YEAR FROM NFCAB.DTEMISSAO) AS ANO_VEN,
   CAST(COPY(CFOP_ITEM.CFOP, 0,20) AS VARCHAR2(20)) AS OPER_VEN,
   CAST(COPY(CFOP_ITEM.CFOP, 0,20) AS VARCHAR2(20)) AS CFOP_VEN,
   CAST(COPY(CFOP_ITEM.NOME, 0, 60) AS VARCHAR2(60)) AS DESC_VEN,
   CAST(NFCFG.ENTRADASAIDA AS VARCHAR(1)) AS SINA_VEN,
   --TOTAL DE TODOS OS PRODUTOS
   CAST((SELECT SUM(INTERNO.VALORTOTAL) FROM NFITEM INTERNO
          WHERE (INTERNO.ESTAB = NFCAB.ESTAB)
            AND (INTERNO.SEQNOTA = NFCAB.SEQNOTA)
   ) AS NUMERIC(18,4)) AS VOLU_VEN,
   --TOTAL APENAS DEFENSIVOS
   CAST(COALESCE((SELECT SUM(INTERNO.VALORTOTAL) FROM NFITEM INTERNO
          INNER JOIN ITEMAGRO
             ON (INTERNO.ITEM = ITEMAGRO.ITEM
				AND ITEMAGRO.MARCA IN (210))
             
          INNER JOIN ITEMGRUPO
             ON (ITEMGRUPO.GRUPO = ITEMAGRO.GRUPO)
             
          INNER JOIN ITEMGRUPO_U
             ON (ITEMGRUPO_U.GRUPO = ITEMGRUPO.GRUPO)
             
          INNER JOIN U_GESTOQUE
             ON (U_GESTOQUE.U_GESTOQUE_ID = ITEMGRUPO_U.U_GESTOQUE_ID)
  
          WHERE (INTERNO.ESTAB = NFCAB.ESTAB)
            AND (INTERNO.SEQNOTA = NFCAB.SEQNOTA)
            AND (U_GESTOQUE.U_GESTOQUE_ID = 1)
            
            --AND (ITEMAGRO.REGISTROMA IS NOT NULL)
   ) ,0)AS NUMERIC(18,4)) AS VDEF_VEN,
   --TOTAL APENAS BASF
   CAST(COALESCE((SELECT SUM(INTERNO.VALORTOTAL) FROM NFITEM INTERNO
          INNER JOIN ITEMAGRO
             ON (INTERNO.item = ITEMAGRO.ITEM)
          WHERE (INTERNO.ESTAB = NFCAB.ESTAB)
            AND (INTERNO.SEQNOTA = NFCAB.SEQNOTA)
            AND (ITEMAGRO.MARCA IN (210))
   ),0)AS NUMERIC(18,4)) AS VIND_VEN

 FROM  NFCAB
 INNER JOIN U_TEMPRESA
 ON U_TEMPRESA.ESTAB = NFCAB.ESTAB
 INNER JOIN NFITEM
   ON (NFITEM.ESTAB = NFCAB.ESTAB)
  AND (NFITEM.SEQNOTA = NFCAB.SEQNOTA)
 LEFT JOIN CFOP CFOP_ITEM
   ON (CFOP_ITEM.CFOP = NFITEM.CFOP)
 INNER JOIN ITEMAGRO
   ON (ITEMAGRO.ITEM = NFITEM.ITEM)
 INNER JOIN NFCFG
   ON (NFCFG.NOTACONF = NFCAB.NOTACONF)

INNER JOIN CONTAMOV
  ON CONTAMOV.NUMEROCM = NFCAB.NUMEROCM
  
LEFT JOIN ENDERECO
    ON ENDERECO.NUMEROCM = NFCAB.NUMEROCM
    AND ENDERECO.SEQENDERECO = NFCAB.SEQENDERECO

LEFT JOIN TBL_BASF ON TBL_BASF.NUMEROCM = NFCAB.NUMEROCM

inner join filial on filial.estab = nfcab.estab
inner join cidade on cidade.cidade = filial.CIDADE


LEFT JOIN NFCFG_U ON NFCFG_U.NOTACONF = NFCFG.NOTACONF
LEFT JOIN U_TIPOOP ON U_TIPOOP.U_TIPOOP_ID = NFCFG_U.U_TIPOOP_ID

  
/* INNER JOIN OS_TBL_BASF_CLIENT TBL
        ON TBL.HASH_CLI = COALESCE(lower(standard_hash(ENDERECO.cnpjf,'MD5')) ,lower(standard_hash(contamov.cnpjf,'MD5')))*/         --upper(sha1(UTL_RAW.CAST_TO_RAW(CONTAMOV.CNPJF)))
        
  WHERE --(NFCAB.ESTAB IN (4,8,13,15,21,27,29))
  ((U_TEMPRESA.INSUMOS='S' and U_TEMPRESA.ESTOQUE = 'S' )OR (U_TEMPRESA.INSUMOS='N' and U_TEMPRESA.ESTOQUE = 'S' ))
    --AND (ITEMAGRO.MARCA IN (210))
	AND (ITEMAGRO.REGISTROMA IS NOT NULL)
    --AND (NFCAB.NOTACONF in (1,4,18,2))
    AND (NFCFG.FISCAL = 'S')
	AND NFCAB.DTEMISSAO BETWEEN '01/04/2026' AND CURRENT_DATE
	AND NOT (U_TIPOOP.TIPOOP IN ('DF-V','DV','DC') AND NFCAB.NUMEROCM IN (1274,39839))
	and cidade.uf = 'SP'

)DADOS
GROUP BY DADOS.CODI_REV, DADOS.MES_VEN, DADOS.ANO_VEN,
       DADOS.OPER_VEN, DADOS.CFOP_VEN, DADOS.DESC_VEN, DADOS.SINA_VEN