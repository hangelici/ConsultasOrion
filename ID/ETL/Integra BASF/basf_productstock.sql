WITH MAX_DATA AS (
    SELECT 
        ISALDO.ITEM,
        ISALDO.ESTAB,
        CODIGOSALDO,
        LOCAL,
        ITEMAGRO.NCM,
        ITEMAGRO.DESCRICAO,
        ITEMAGRO.UNIDADE,
        ITEMAGRO.NROCODBAR,
        MAX(TO_DATE('01/' || LPAD(COALESCE(ISALDO.MES, 1), 2, '0') || '/' || COALESCE(ISALDO.ANO, 1), 'DD/MM/YYYY')) AS DATA_MAX
    FROM ITEMSALDO ISALDO
    INNER JOIN ITEMAGRO ON ITEMAGRO.ITEM = ISALDO.ITEM
    WHERE
    ISALDO.codigosaldo in (1,2,20)
    AND (TO_DATE('01/' || LPAD(COALESCE(ISALDO.MES, 1), 2, '0') || '/' || COALESCE(ISALDO.ANO, 1), 'DD/MM/YYYY')) <= CURRENT_DATE
    AND ITEMAGRO.MARCA = 210
    -- 1 disponivel
    -- 2 fisico
    -- 20 em transito
  GROUP BY ISALDO.ITEM, ISALDO.ESTAB,CODIGOSALDO,LOCAL,ITEMAGRO.NCM, ITEMAGRO.DESCRICAO,ITEMAGRO.UNIDADE,ITEMAGRO.NROCODBAR
)
    SELECT
    ITEMAGROESTAB.ESTAB AS CODI_REV,
    '210' as CODI_FAB,
    ITEMAGROESTAB.ITEM AS CODI_PRO,
    SUBSTR(MD.DESCRICAO,0,60) AS DESC_PRO,
    MD.NCM AS NCMP_PRO,
    MD.UNIDADE AS UNID_PRO,
    MD.NROCODBAR AS BARR_PRO,
    RPAD(TO_CHAR(CURRENT_DATE,'YYYY/MM/DD'),19,' 00:00:00') AS DATE_PRO,
    NULL AS LOTE_PRO,
    NULL AS DVEN_PRO,
    SUM(CASE WHEN MD.CODIGOSALDO = 2 THEN ITEMSALDO.SALDOQUANTIDADE ELSE 0 END) QTDE_PRO,
    SUM(CASE WHEN MD.CODIGOSALDO = 1 THEN ITEMSALDO.SALDOQUANTIDADE ELSE 0 END) QTDI_PRO,
    SUM(CASE WHEN MD.CODIGOSALDO = 20 THEN ITEMSALDO.SALDOQUANTIDADE ELSE 0 END) QTTR_PRO,
    0 AS QTBL_PRO
    FROM ITEMAGROESTAB

    INNER JOIN FILIAL ON FILIAL.ESTAB = ITEMAGROESTAB.ESTAB
    LEFT JOIN ITEMSALDO ON 
        ITEMSALDO.ITEM = ITEMAGROESTAB.ITEM 
        AND ITEMSALDO.ESTAB = ITEMAGROESTAB.ESTAB 

    INNER JOIN MAX_DATA MD 
        ON MD.ITEM = ITEMSALDO.ITEM 
        AND MD.ESTAB = ITEMSALDO.ESTAB 
        AND MD.CODIGOSALDO = ITEMSALDO.CODIGOSALDO
        AND MD.LOCAL = ITEMSALDO.LOCAL
        AND TO_DATE('01/' || LPAD(COALESCE(ITEMSALDO.MES, 1), 2, '0') || '/' || COALESCE(ITEMSALDO.ANO, 1), 'DD/MM/YYYY') = MD.DATA_MAX

GROUP BY
ITEMAGROESTAB.ESTAB,
ITEMAGROESTAB.ITEM,
MD.DESCRICAO,
MD.NCM ,
 MD.UNIDADE,
MD.NROCODBAR