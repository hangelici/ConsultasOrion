with clientes as (
   select nfcab.numerocm
   from nfcab
   inner join nfitem on
      nfitem.estab = nfcab.estab
      and nfitem.seqnota = nfcab.seqnota
   inner join itemagro on itemagro.item = nfitem.item
   where itemagro.marca = 210
)
SELECT
CAST(COPY(CONTAMOV.NUMEROCM, 0,20) AS VARCHAR(20))||' - '||SUBSTR(CONTAMOV.cnpjf,length(CONTAMOV.cnpjf)-1,2)||' - 0' AS CODI_CLI,
--CAST(COPY(CONTAMOV.NUMEROCM, 0,20) AS VARCHAR(20))||' - '||SUBSTR(cnpjf,length(cnpjf)-1,2)||' - 0' AS CODI_CLI
CAST(COPY(COALESCE(CONTAMOV.CNPJF,'0'), 0,14) AS VARCHAR(14)) AS CNPJ_CLI,
CAST(COPY(COALESCE(CONTAMOV.NOME,'0'), 0,65) AS VARCHAR(65)) AS NOME_CLI, 
CAST(COPY(COALESCE(CONTAMOV.ENDERECO,'0'), 0, 60) AS VARCHAR(60)) AS ENCO_CLI,
CAST(COALESCE(CONTAMOV.NUMEROEND,'0') AS VARCHAR(10)) AS NUME_CLI,
CAST(COPY(COALESCE(CONTAMOV.BAIRRO,'0'), 0,40) AS VARCHAR(40))AS BAIR_CLI,
CAST(COPY(COALESCE(CONTAMOV.COMPLEMENTO,'0'), 0, 60) AS VARCHAR(60)) AS COMP_CLI,
CAST(COPY(COALESCE(CONTAMOV.CEP,'0'), 0,9) AS VARCHAR(9)) AS CEPC_CLI, 
CONTAMOV.INSCESTAD as INSC_CLI,
CAST((UF.CODIGO * 100000) + (CIDADE.IBGE) AS VARCHAR(7)) AS MUNI_CLI,
NULL AS CSEG_CLI,
NULL AS DSEG_CLI,
NULL AS CNAE_CLI

FROM CONTAMOV

LEFT JOIN PPESCLI
ON (PPESCLI.CLIENTE = CONTAMOV.NUMEROCM)

LEFT JOIN PPESSFOR
ON (PPESSFOR.FORNECEDOR = CONTAMOV.NUMEROCM)

INNER JOIN CIDADE
ON (CIDADE.CIDADE = CONTAMOV.CIDADE)

INNER JOIN UF
ON (UF.UF = CIDADE.UF)

LEFT JOIN CIDADE CID_COB
ON (CID_COB.CIDADE = CONTAMOV.CIDADE)

INNER JOIN UF UF_COB
ON (UF_COB.UF = CID_COB.UF)


INNER JOIN CONTAMOV_U ON CONTAMOV_U.NUMEROCM = CONTAMOV.NUMEROCM

WHERE  CONTAMOV_U.PROGRAMA_BASF = 'S'
AND EXISTS  (
   SELECT 1 FROM CLIENTES 
   WHERE CLIENTES.NUMEROCM = CONTAMOV.NUMEROCM
)

UNION ALL

SELECT 
CAST(COPY(ENDERECO.NUMEROCM, 0,20) AS VARCHAR(20))||' - '||SUBSTR(ENDERECO.cnpjf,length(ENDERECO.cnpjf)-1,2)||' - '||CAST(COPY(ENDERECO.SEQENDERECO, 0,20) AS VARCHAR(20)) AS CODI_CLI,
CAST(COPY(COALESCE(ENDERECO.CNPJF,'0'), 0,14) AS VARCHAR(14)) AS CNPJ_CLI,
CAST(COPY(COALESCE(ENDERECO.NOME,'0'), 0,65) AS VARCHAR(65)) AS NOME_CLI, 
CAST(COPY(COALESCE(ENDERECO.ENDERECO,'0'), 0, 60) AS VARCHAR(60)) AS ENCO_CLI,
CAST(COALESCE(ENDERECO.NUMEROEND,'0') AS VARCHAR(10)) AS NUME_CLI,
CAST(COPY(COALESCE(ENDERECO.BAIRRO,'0'), 0,40) AS VARCHAR(40))AS BAIR_CLI,
CAST(COPY(COALESCE(ENDERECO.COMPLEMENTO,'0'), 0, 60) AS VARCHAR(60)) AS COMP_CLI,
CAST(COPY(COALESCE(ENDERECO.CEP,'0'), 0,9) AS VARCHAR(9)) AS CEPC_CLI, 
ENDERECO.CREDENCIALAGRO AS INSC_CLI,
CAST((UF.CODIGO * 100000) + (CIDADE.IBGE) AS VARCHAR(7)) AS MUNI_CLI,
NULL AS CSEG_CLI,
NULL AS DSEG_CLI,
NULL AS CNAE_CLI

FROM ENDERECO

LEFT JOIN PPESCLI
ON (PPESCLI.CLIENTE = ENDERECO.NUMEROCM)

LEFT JOIN PPESSFOR
ON (PPESSFOR.FORNECEDOR = ENDERECO.NUMEROCM)

INNER JOIN CIDADE
ON (CIDADE.CIDADE = ENDERECO.CIDADE)

INNER JOIN UF
ON (UF.UF = CIDADE.UF)

LEFT JOIN CIDADE CID_COB
ON (CID_COB.CIDADE = ENDERECO.CIDADE)


INNER JOIN UF UF_COB
ON (UF_COB.UF = CID_COB.UF)

INNER JOIN CONTAMOV_U ON CONTAMOV_U.NUMEROCM = ENDERECO.NUMEROCM

WHERE CONTAMOV_U.PROGRAMA_BASF = 'S'
AND EXISTS  (
   SELECT 1 FROM CLIENTES 
   WHERE CLIENTES.NUMEROCM = ENDERECO.NUMEROCM
)


UNION ALL

