WITH 
        META AS
        (
             SELECT 
        sum(T.QTD) AS META
    FROM U_METARTV T
        INNER JOIN
            (SELECT
                MAX(seqhist) AS maxhist,
                codconsultor,
                segmento,
                codestoque,
                safra,
                osestab
            FROM U_METARTV
            WHERE
                    ativo = 'S'
                AND segmento = 2 --cuidado aqui: se quer só segmento 2 na query, mantenha esse filtro
            GROUP BY
                codconsultor,
                segmento,
                codestoque,
                safra,
                osestab
            ) ultimo
            ON  ultimo.maxhist      = T.seqhist
            AND ultimo.codconsultor = T.codconsultor
            AND ultimo.segmento     = T.segmento
            AND ultimo.codestoque   = T.codestoque
            AND ultimo.safra        = T.safra
            AND ultimo.osestab      = T.osestab
        INNER JOIN FILIAL ON  FILIAL.ESTAB = T.OSESTAB
        INNER JOIN CIDADE ON  CIDADE.CIDADE = FILIAL.CIDADE
        INNER JOIN UF ON  CIDADE.UF = UF.UF
        INNER JOIN U_TEMPRESA ON U_TEMPRESA.ESTAB = FILIAL.ESTAB
    WHERE
    cast(t.data as date) BETWEEN CAST(TO_DATE(:startDate) AS DATE) AND CAST(TO_DATE(:endDate) AS DATE)
    AND U_TEMPRESA.TRADING <> 'S'
    AND T.ATIVO = 'S'
    AND T.SEGMENTO = 2
),
COMPRADO AS (
SELECT
SUM(QTDSC - NVL(QTDCANC,0)) AS COMPRADO,
SUM(QTDMES) AS QTDMES_ACUMULADO
FROM (

SELECT
    (COALESCE(ROUND((CONTRATOITE.QUANTIDADE / 60), 2), 0)) AS QTDSC,
     0 AS QTDCANC,
    (ARREDONDAR(DIVIDE(CASE WHEN CAST(CONTRATO.DTEMISSAO AS DATE) BETWEEN TRUNC(SYSDATE, 'MM') AND TRUNC(LAST_DAY(SYSDATE)) THEN CONTRATOITE.QUANTIDADE ELSE 0 END,60),2)) AS QTDMES
   
FROM CONTRATO

INNER JOIN (
    SELECT DISTINCT
        ESTAB,
        CONTRATO,
        NUMEROCM
    FROM OS_CONTRATOCOM
    WHERE META > 0
) CONTRATOCOM
    ON CONTRATOCOM.CONTRATO = CONTRATO.CONTRATO
    AND CONTRATOCOM.ESTAB = CONTRATO.ESTAB

INNER JOIN CONTRATOITE
    ON CONTRATOITE.ESTAB = CONTRATO.ESTAB
    AND CONTRATOITE.CONTRATO = CONTRATO.CONTRATO

INNER JOIN CONTRATOCFG ON  CONTRATOCFG.CONTCONF = CONTRATO.CONTCONF
INNER JOIN CONTRATOCFG_U ON  CONTRATOCFG_U.CONTCONF = CONTRATOCFG.CONTCONF
INNER JOIN U_TIPOCTR ON  U_TIPOCTR.U_TIPOCTR_ID = CONTRATOCFG_U.U_TIPOCTR_ID
inner join u_tempresa
                    on  u_tempresa.estab = contrato.estab

WHERE CAST(CONTRATO.dtlimentimp AS DATE) BETWEEN CAST(TO_DATE(:startDate) AS DATE) AND CAST(TO_DATE(:endDate) AS DATE)
and CAST(CONTRATO.dtemissao AS DATE) BETWEEN CAST(TO_DATE(:startDate) AS DATE) AND CAST(TO_DATE(:endDate) AS DATE)
AND CONTRATO.DTLIMENTIMP IS NOT NULL
AND U_TIPOCTR.TIPOCTR IN ('CTR-C')
AND u_tempresa.trading <> 'S'

union all

SELECT
    (COALESCE(ROUND((CONTRATOITE.QUANTIDADE / 60), 2), 0)) AS QTDSC,
     0 AS QTDCANC,
    case 
        when extract(month from sysdate) = 7 then 
            (ARREDONDAR(DIVIDE(CASE WHEN CAST(CONTRATO.DTEMISSAO AS DATE) BETWEEN TRUNC(SYSDATE, 'MM') AND TRUNC(LAST_DAY(SYSDATE)) THEN CONTRATOITE.QUANTIDADE ELSE 0 END,60),2)) 
        else 0
    end  QTDMES
    --(ARREDONDAR(DIVIDE(CASE WHEN CAST(CONTRATO.DTEMISSAO AS DATE) BETWEEN TRUNC(SYSDATE, 'MM') AND TRUNC(LAST_DAY(SYSDATE)) THEN CONTRATOITE.QUANTIDADE ELSE 0 END,60),2)) AS QTDMES
   
FROM CONTRATO

INNER JOIN (
    SELECT DISTINCT
        ESTAB,
        CONTRATO,
        NUMEROCM
    FROM OS_CONTRATOCOM
    WHERE META > 0
) CONTRATOCOM
    ON CONTRATOCOM.CONTRATO = CONTRATO.CONTRATO
    AND CONTRATOCOM.ESTAB = CONTRATO.ESTAB

INNER JOIN CONTRATOITE
    ON CONTRATOITE.ESTAB = CONTRATO.ESTAB
    AND CONTRATOITE.CONTRATO = CONTRATO.CONTRATO

INNER JOIN CONTRATOCFG ON  CONTRATOCFG.CONTCONF = CONTRATO.CONTCONF
INNER JOIN CONTRATOCFG_U ON  CONTRATOCFG_U.CONTCONF = CONTRATOCFG.CONTCONF
INNER JOIN U_TIPOCTR ON  U_TIPOCTR.U_TIPOCTR_ID = CONTRATOCFG_U.U_TIPOCTR_ID
inner join u_tempresa
                    on  u_tempresa.estab = contrato.estab

WHERE CAST(CONTRATO.dtlimentimp AS DATE) BETWEEN CAST(TO_DATE(:startDate) AS DATE) AND CAST(TO_DATE(:endDate) AS DATE)
and CAST(CONTRATO.dtemissao AS DATE) < CAST(TO_DATE(:startDate) AS DATE)
AND CONTRATO.DTLIMENTIMP IS NOT NULL
AND U_TIPOCTR.TIPOCTR IN ('CTR-C')
AND u_tempresa.trading <> 'S'

UNION ALL

-- CANCELADOS
    SELECT
        0 AS QTDSC,
        COALESCE(ROUND((CONTRATOCANC.QUANTIDADE / 60), 2),0) AS QTDCANC,
    CASE
        WHEN COALESCE(
                CONTRATOCANC.DTCANCELAMENTO,
                CONTRATOCANC.DATA
            )
        BETWEEN TRUNC(SYSDATE, 'MM') AND TRUNC(LAST_DAY(SYSDATE)) THEN COALESCE(ROUND((CONTRATOCANC.QUANTIDADE / 60), 2),0)*-1 ELSE 0

        END QTDMES
    FROM CONTRATO

    INNER JOIN CONTRATOITE
        ON CONTRATOITE.ESTAB = CONTRATO.ESTAB
        AND CONTRATOITE.CONTRATO = CONTRATO.CONTRATO

    INNER JOIN (
        SELECT DISTINCT
            ESTAB,
            CONTRATO,
            NUMEROCM
        FROM OS_CONTRATOCOM
        WHERE META > 0
    ) CONTRATOCOM
        ON CONTRATOCOM.CONTRATO = CONTRATO.CONTRATO
        AND CONTRATOCOM.ESTAB = CONTRATO.ESTAB

    INNER JOIN CONTRATOCANC
        ON CONTRATOCANC.CONTRATO = CONTRATOITE.CONTRATO
        AND CONTRATOCANC.ESTAB = CONTRATOITE.ESTAB
        AND CONTRATOCANC.SEQITEM = CONTRATOITE.SEQITEM

INNER JOIN CONTRATOCFG ON  CONTRATOCFG.CONTCONF = CONTRATO.CONTCONF
INNER JOIN CONTRATOCFG_U ON  CONTRATOCFG_U.CONTCONF = CONTRATOCFG.CONTCONF
INNER JOIN U_TIPOCTR ON  U_TIPOCTR.U_TIPOCTR_ID = CONTRATOCFG_U.U_TIPOCTR_ID
INNER JOIN U_TEMPRESA ON  U_TEMPRESA.ESTAB = CONTRATO.ESTAB

WHERE  U_TIPOCTR.TIPOCTR IN ('CTR-C')
AND u_tempresa.trading <> 'S'
AND
(CASE
            WHEN CONTRATO.DTLIMENTIMP >
                 COALESCE(
                     CONTRATOCANC.DTCANCELAMENTO,
                     CONTRATOCANC.DATA
                 )
            THEN CONTRATO.DTLIMENTIMP
            ELSE COALESCE(
                CONTRATOCANC.DTCANCELAMENTO,
                CONTRATOCANC.DATA
            )
        END) BETWEEN CAST(TO_DATE(:startDate) AS DATE) AND CAST(TO_DATE(:endDate) AS DATE)
)DADOS

)
SELECT
META.META,
COMPRADO.COMPRADO,
COMPRADO.QTDMES_ACUMULADO
FROM
META
CROSS JOIN COMPRADO