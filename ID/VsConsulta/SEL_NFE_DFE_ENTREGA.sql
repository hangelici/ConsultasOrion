SELECT
  CASE WHEN (COALESCE(END_ENTREGA.SEQENDERECO,0) <> 0) AND (COALESCE(END_ENTREGA.CNPJF,'') <> ' ') THEN
    END_ENTREGA.CNPJF
  ELSE
    ENTREGA.CNPJF
  END AS CNPJCPF,
  COPY(COALESCE(END_ENTREGA.ENDERECO,    ENTREGA.ENDERECO), 1, 60) AS XLGR,
  COALESCE(END_ENTREGA.NUMEROEND,   ENTREGA.NUMEROEND) AS NRO,
  COALESCE(END_ENTREGA.COMPLEMENTO, ENTREGA.COMPLEMENTO) AS XCPL,
  COALESCE(END_ENTREGA.BAIRRO,      ENTREGA.BAIRRO) AS XBAIRRO,
  COPY(COALESCE(END_ENTREGA.NOME,      ENTREGA.NOME), 1, 60) AS XNOME,
  COALESCE(
      CAST((UF_END_ENTREGA.CODIGO * 100000) + CID_END_ENTREGA.IBGE AS INTEGER),
      CAST((UF_ENTREGA.CODIGO * 100000) + CID_ENTREGA.IBGE AS INTEGER)) AS CMUN,
  UF_ENTREGA.PAISSIGLA AS XPAIS,
  COALESCE(CID_END_ENTREGA.PAIS,  CID_ENTREGA.PAIS) AS CPAIS,
  COALESCE(CID_END_ENTREGA.NOME,  CID_ENTREGA.NOME) AS XMUN,
  COALESCE(CID_END_ENTREGA.UF,    CID_ENTREGA.UF) AS UF,
  COALESCE(CID_END_ENTREGA.CEP,    CID_ENTREGA.CEP) AS CEP
  FROM NFCAB
  , CONTAMOV ENTREGA
  , ENDERECO END_ENTREGA
  , CIDADE CID_END_ENTREGA
  , CIDADE CID_ENTREGA
  , UF UF_END_ENTREGA
  , UF UF_ENTREGA
WHERE (NFCAB.ESTAB = :ESTAB)
  AND (NFCAB.SEQNOTA = :IDNOTA)
--  INNER JOIN CONTAMOV ENTREGA
   AND (NFCAB.PESSENTREGA = ENTREGA.NUMEROCM(+))
--  LEFT JOIN ENDERECO END_ENTREGA
   AND (NFCAB.PESSENTREGA = END_ENTREGA.NUMEROCM(+))
   AND (NFCAB.SEQENDENTREGA = END_ENTREGA.SEQENDERECO(+))
--  LEFT JOIN CIDADE CID_END_ENTREGA
   AND (END_ENTREGA.CIDADE = CID_END_ENTREGA.CIDADE(+))
--  LEFT JOIN CIDADE CID_ENTREGA
   AND (ENTREGA.CIDADE = CID_ENTREGA.CIDADE(+))
--  LEFT JOIN UF UF_END_ENTREGA
   AND(CID_END_ENTREGA.UF = UF_END_ENTREGA.UF(+))
--  LEFT JOIN UF UF_ENTREGA
   AND(CID_ENTREGA.UF = UF_ENTREGA.UF(+))
ORDER BY NFCAB.ESTAB, NFCAB.SEQNOTA