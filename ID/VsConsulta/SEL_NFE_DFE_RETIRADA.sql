SELECT 
  CASE WHEN (COALESCE(END_RETIRA.SEQENDERECO,0) <> 0) AND (COALESCE(END_RETIRA.CNPJF,'') <> ' ') THEN
      END_RETIRA.CNPJF
  ELSE 
      RETIRA.CNPJF
  END AS CNPJF,
  COPY(COALESCE(END_RETIRA.ENDERECO,    RETIRA.ENDERECO), 1, 60) AS XLGR,
  COALESCE(END_RETIRA.NUMEROEND,   RETIRA.NUMEROEND) AS NRO,
  COALESCE(END_RETIRA.COMPLEMENTO, RETIRA.COMPLEMENTO) AS XCPL,
  COALESCE(END_RETIRA.BAIRRO,      RETIRA.BAIRRO) AS XBAIRRO,
  COPY(COALESCE(END_RETIRA.NOME,   RETIRA.NOME),1, 60) AS XNOME,
  COALESCE(
      CAST((UF_END_RETIRA.CODIGO * 100000) + CID_END_RETIRA.IBGE AS INTEGER),
      CAST((UF_RETIRA.CODIGO * 100000) + CID_RETIRA.IBGE AS INTEGER) ) AS CMUN,
  UF_RETIRA.PAISSIGLA AS XPAIS,
  COALESCE(CID_END_RETIRA.PAIS, CID_RETIRA.PAIS) AS CPAIS,
  COALESCE(CID_END_RETIRA.NOME, CID_RETIRA.NOME) AS XMUN,
  COALESCE(CID_END_RETIRA.UF,   CID_RETIRA.UF) AS UF,
  COALESCE(CID_END_RETIRA.CEP,   CID_RETIRA.CEP) AS CEP
  FROM NFCAB
  , CONTAMOV RETIRA
  , ENDERECO END_RETIRA
  , CIDADE CID_END_RETIRA
  ,  CIDADE CID_RETIRA
  , UF UF_END_RETIRA
  , UF UF_RETIRA
WHERE (NFCAB.ESTAB = :ESTAB)
  AND (NFCAB.SEQNOTA = :IDNOTA)
--  INNER JOIN CONTAMOV RETIRA
  AND (NFCAB.PESSRETIRADA = RETIRA.NUMEROCM(+))
--  LEFT JOIN ENDERECO END_RETIRA
   AND (NFCAB.PESSRETIRADA = END_RETIRA.NUMEROCM(+))
   AND (NFCAB.SEQENDRETIRADA = END_RETIRA.SEQENDERECO(+))
--  LEFT JOIN CIDADE CID_END_RETIRA
   AND (END_RETIRA.CIDADE = CID_END_RETIRA.CIDADE(+))
--  LEFT JOIN CIDADE CID_RETIRA
   AND (RETIRA.CIDADE = CID_RETIRA.CIDADE(+))
--  LEFT JOIN UF UF_END_RETIRA
   AND(CID_END_RETIRA.UF = UF_END_RETIRA.UF(+))
--  LEFT JOIN UF UF_RETIRA
   AND(CID_RETIRA.UF = UF_RETIRA.UF(+))