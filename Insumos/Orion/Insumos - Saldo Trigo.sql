      ITEMAGRO.DESCRICAO||'-'||ITEMAGRO.ITEM AS DESCRICAO_CULTIVAR,
       U_AGRPROD.U_AGRPROD_ID AGR,
        U_AGRPROD.U_AGRPROD_ID ||'-'||U_AGRPROD.DESCAGRUPA CULTIVAR,
