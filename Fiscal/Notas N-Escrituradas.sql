WITH EVENTO AS (
    SELECT
        N.CHAVE,
        N.TPEVENTO,
        N.XEVENTO
    FROM U_NOTASSIEG_EVENTOS N
    INNER JOIN (
        SELECT
            CHAVE,
            MAX(DATAHORA) AS DT
        FROM U_NOTASSIEG_EVENTOS
        GROUP BY CHAVE
    ) MAXIMO
        ON MAXIMO.CHAVE = N.CHAVE
       AND MAXIMO.DT = N.DATAHORA
),
ITEM AS (
    SELECT
        CHAVE,
        SUM(VALOR) AS VALOR_TOTAL,
        MIN(VLRUNITARIO) AS VLRUNITARIO,
        MIN(NCM) AS NCM,
        MIN(UNIDADE) AS UNIDADE
    FROM U_NOTASSIEG_ITENS
    GROUP BY CHAVE
)
SELECT DISTINCT
    NOTAS.ESTAB,
    FILIAL.REDUZIDO,
    ITEM.UNIDADE,
    ITEMAGRO.ITEM,
    ITEMAGRO.DESCRICAO,
    NOTAS.VPROD,
    ITEM.VLRUNITARIO,
    ROUND(ITEM.VALOR_TOTAL / NULLIF(ITEM.VLRUNITARIO, 0), 4) AS QTD_CALC,
    NOTAS.CNPJ_DESTIN,
    NOTAS.NOTA,
    TO_CHAR(TRUNC(NOTAS.DTEMISSAO), 'DD/MM/YYYY') AS DTEMISSAO,
    TRUNC(SYSDATE) - TRUNC(NOTAS.DTEMISSAO) AS DIAS,

    CASE
        WHEN TRUNC(SYSDATE) - TRUNC(NOTAS.DTEMISSAO) <= 4 THEN 1
        ELSE 0
    END AS ATE_4_DIAS,

    CASE
        WHEN TRUNC(SYSDATE) - TRUNC(NOTAS.DTEMISSAO) BETWEEN 5 AND 9 THEN 1
        ELSE 0
    END AS ENTRE_5_9_DIAS,

    CASE
        WHEN TRUNC(SYSDATE) - TRUNC(NOTAS.DTEMISSAO) >= 10 THEN 1
        ELSE 0
    END AS MAIOR_10_DIAS,

    NOTAS.NOMEMI,
    NOTAS.CNPJ_EMITENTE,
    NOTAS.CHAVEACESSONFE,
    NFCABPRODUTOR.CHAVEACESSONFP,
    NOTAS.STATUS,
    NOTAS.CFOP,

    COALESCE(EVENTO.TPEVENTO, CAST(NOTAS.TP_EVENTO AS VARCHAR2(20))) AS TP_EVENTO,
    COALESCE(EVENTO.XEVENTO, NOTAS.DESC_EVENTO) AS DESC_EVENTO,

    NOTAS.UF,
    NOTAS.IE,
    NOTAS.MOD,

    CASE
        WHEN COALESCE(ENDERECO.PRODUTOREND, CONTAMOV.PRODUTOR) IS NULL THEN 'CNPJ/CPF NÃO ENCONTRADO NOS CADASTROS'
        WHEN COALESCE(ENDERECO.PRODUTOREND, CONTAMOV.PRODUTOR) = 'N' THEN 'NÃO É PRODUTOR'
        WHEN COALESCE(ENDERECO.PRODUTOREND, CONTAMOV.PRODUTOR) = 'S' THEN 'PRODUTOR'
        ELSE COALESCE(ENDERECO.PRODUTOREND, CONTAMOV.PRODUTOR)
    END AS PRODUTOR,

    1 AS QTD

FROM U_NOTASSIEG NOTAS

INNER JOIN FILIAL
    ON FILIAL.ESTAB = NOTAS.ESTAB
   AND FILIAL.CNPJ = NOTAS.CNPJ_DESTIN



LEFT JOIN NFCAB
    ON NFCAB.ESTAB = NOTAS.ESTAB
   AND NFCAB.CHAVEACESSONFE = NOTAS.CHAVEACESSONFE

LEFT JOIN CONTAMOV
    ON CONTAMOV.CNPJF = NOTAS.CNPJ_EMITENTE

LEFT JOIN ENDERECO
    ON ENDERECO.CNPJF = NOTAS.CNPJ_EMITENTE

LEFT JOIN EVENTO
    ON EVENTO.CHAVE = NOTAS.CHAVEACESSONFE

LEFT JOIN NFCABPRODUTOR
    ON NFCABPRODUTOR.ESTAB = NOTAS.ESTAB
   AND NFCABPRODUTOR.CHAVEACESSONFP = NOTAS.CHAVEACESSONFE

LEFT JOIN U_TEMPRESA
    ON U_TEMPRESA.ESTAB = FILIAL.ESTAB

LEFT JOIN ITEM
    ON ITEM.CHAVE = NOTAS.CHAVEACESSONFE
    
   LEFT JOIN U_MOTIVO_TRADING ON
    U_MOTIVO_TRADING.CHAVEACESSO = NOTAS.CHAVEACESSONFE    

LEFT JOIN (
    SELECT
        ITEM,
        DESCRICAO,
        CLASFISCAL,
        ROW_NUMBER() OVER (
            PARTITION BY CLASFISCAL
            ORDER BY ITEM
        ) RN
    FROM ITEMAGRO
) ITEMAGRO
    ON ITEMAGRO.CLASFISCAL = ITEM.NCM
   AND ITEMAGRO.RN = 1

WHERE NOTAS.MOD = 55
  AND NOTAS.STATUS <> 101
  AND NFCAB.NOTA IS NULL
  AND NFCABPRODUTOR.CHAVEACESSONFP IS NULL
  AND NOTAS.DTEMISSAO BETWEEN :DTINI AND :DTFIM
  AND (
        NOTAS.UF = 'MT'
        OR (
            LENGTH(REGEXP_REPLACE(NOTAS.CNPJ_EMITENTE, '[^0-9]', '')) = 14
            AND NOTAS.UF <> 'MT'
        )
        OR (
            LENGTH(REGEXP_REPLACE(NOTAS.CNPJ_EMITENTE, '[^0-9]', '')) = 11
            AND (NOTAS.IE IS NULL OR TRIM(NOTAS.IE) = '')
            AND NOTAS.UF <> 'MT'
        )
      )
  AND (0 IN (:ESTAB) OR NOTAS.ESTAB IN (:ESTAB))
  AND EVENTO.TPEVENTO NOT IN ('110111','210220','610131','610611','610601','610615','210240')
  --AND U_TEMPRESA.GRAOS = 'S'
   and NOT EXISTS (
    SELECT 1
    FROM U_MOTIVO_TRADING MT
    WHERE MT.CHAVEACESSO = NOTAS.CHAVEACESSONFE)