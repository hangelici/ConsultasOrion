-- ## DUP A Pagar
WITH BAIXAS AS (
    SELECT
    EMPRESA,
    DUPPAG,
    FORNECEDOR,
    MAX(DTPAGTO) AS DTPAGTO,
    SUM(VALOR) AS VLR,
    SUM(PPDUPPAG.VALOR * CASE WHEN PPDUPPAG.TIPOPAG IN ('P','J') THEN 1 ELSE -1 END) AS PAGO,
    SUM(CASE WHEN PPDUPPAG.TIPOPAG IN ('J') THEN PPDUPPAG.VALOR ELSE 0 END) JUROS,
    SUM(CASE WHEN PPDUPPAG.TIPOPAG IN ('P') THEN PPDUPPAG.VALOR ELSE 0 END) PAGODPL
    FROM PPDUPPAG

    WHERE TIPOPAG in ('P','J')
    AND DTPAGTO <= :DTPOSICAO
   -- AND (IDCTB IS NOT NULL OR TIPOACERTO = 'DP')
    AND 
        (
            EXISTS (
                SELECT
                1
                FROM PPDUPPAD
                 WHERE
                 (PPDUPPAD.EMPRESA = PPDUPPAG.EMPRESA)
                           AND (PPDUPPAD.ESTABFORNECEDOR = PPDUPPAG.ESTABFORNECEDOR)
                           AND (PPDUPPAD.FORNECEDOR = PPDUPPAG.FORNECEDOR)
                           AND (PPDUPPAD.DUPPAG = PPDUPPAG.DUPPAG)
                           AND (PPDUPPAD.SEQPAGTODU = PPDUPPAG.SEQPAGTODU)
                )
             OR
             EXISTS (
                 SELECT
                 1
                 FROM PPADUCM
                 WHERE
                 (PPADUCM.EMPRESA = PPDUPPAG.EMPRESA)
                               AND (PPADUCM.ESTABFORNECEDOR = PPDUPPAG.ESTABFORNECEDOR)
                               AND (PPADUCM.FORNECEDOR = PPDUPPAG.FORNECEDOR)
                               AND (PPADUCM.DUPPAG = PPDUPPAG.DUPPAG)
                               AND (PPADUCM.SEQPAGTODU = PPDUPPAG.SEQPAGTODU)
                )
            OR
            EXISTS (
                SELECT
                1 
                FROM PPDUPPADUP
                WHERE (PPDUPPADUP.EMPRESA         = PPDUPPAG.EMPRESA)
                        AND (PPDUPPADUP.ESTABFORNECEDOR = PPDUPPAG.ESTABFORNECEDOR)
                        AND (PPDUPPADUP.FORNECEDOR         = PPDUPPAG.FORNECEDOR)
                        AND (PPDUPPADUP.DUPPAG             = PPDUPPAG.DUPPAG)
                        AND (PPDUPPADUP.SEQPAGTODU         = PPDUPPAG.SEQPAGTODU)
                )
            OR
            EXISTS (
                SELECT
                1
                FROM PPADUCHE
                WHERE (PPADUCHE.EMPRESA = PPDUPPAG.EMPRESA)
                            AND (PPADUCHE.ESTABFORNECEDOR = PPDUPPAG.ESTABFORNECEDOR)
                            AND (PPADUCHE.FORNECEDOR = PPDUPPAG.FORNECEDOR)
                            AND (PPADUCHE.DUPPAG = PPDUPPAG.DUPPAG)
                            AND (PPADUCHE.SEQPAGTODU = PPDUPPAG.SEQPAGTODU)
            
                )
            OR
            EXISTS (
                SELECT
                1
                FROM PPADUCHR
                WHERE (PPADUCHR.EMPRESA = PPDUPPAG.EMPRESA)
                            AND (PPADUCHR.ESTABFORNECEDOR = PPDUPPAG.ESTABFORNECEDOR)
                            AND (PPADUCHR.FORNECEDOR = PPDUPPAG.FORNECEDOR)
                            AND (PPADUCHR.DUPPAG = PPDUPPAG.DUPPAG)
                            AND (PPADUCHR.SEQPAGTODU = PPDUPPAG.SEQPAGTODU)
                )
        )
    GROUP BY EMPRESA,DUPPAG,FORNECEDOR
)
select
'Duplicatas a Pagar' AS TIPO,
'DPL-P' AS TIPO_DOC,
'PAGAR' AS RECDESP,
FILIAL.REDUZIDO AS FILIAL,
FILIAL.ESTAB,
CONTAMOV.NOME AS CLIENTE,
CONTAMOV.NUMEROCM AS NUMEROCM,
PPORTADO.DESCRICAO AS PORTADOR,
PANALITI.DESCRICAO AS TRANSACAO,
PDUPPAGA.HISTORICO HISTORICO,
PDUPPAGA.DUPPAG DOCUMENTO,
--  COALESCE(CENCUSCE.cencuscod || ' - ' || CENCUSCE.centrocus || ' - ' || CENCUSCE.descricao, 'SEM CENTRO DE CUSTO') CENTROCUSTO,
--(PDUPPAGA.VALOR - COALESCE(BAIXAS.VLR,0))  AS SALDO, 
  (PDUPPAGA.VALOR - COALESCE(BAIXAS.PAGODPL,0))  AS SALDO, 
        CASE
            
            WHEN COALESCE(BAIXAS.PAGODPL,0) = 0
              THEN 'ABERTA'
            ELSE
              'PARCIALMENTE BAIXADA'
          END STATUS,
          
--CASE WHEN CAST(PDUPPAGA.DTVENCTO AS DATE) > CURRENT_DATE THEN 'N' ELSE 'S' END AS VENCIDO,
PDUPPAGA.VALOR  AS VALOR,
        
(COALESCE(BAIXAS.PAGO,0)) AS VALORPAGO,
(COALESCE(BAIXAS.PAGODPL,0)) AS VALOR_PAG_DPL,  
(COALESCE(BAIXAS.JUROS,0)) as VALOR_JUROS,

PDUPPAGA.DTEMISSAO AS DTEMISSAO,
PDUPPAGA.DTENTRADA AS DTENTRADA,
TO_CHAR(PDUPPAGA.DTVENCTO,'DD/MM/YYYY') AS DTVENCTO,
TO_CHAR(BAIXAS.DTPAGTO,'DD/MM/YYYY') AS DTPAGTO,
PDUPPAGA.DTBASEJUROS AS DTBASEJUROS,
PDUPPAGA.DTVENCTO AS DTJS,
          
          
       CASE WHEN  U_TEMPRESA.INSUMOS = 'N' AND U_TEMPRESA.GRAOS = 'S' AND U_TEMPRESA.OUTROS='S' THEN 'O'
           WHEN  U_TEMPRESA.INSUMOS = 'S' AND U_TEMPRESA.GRAOS = 'S' AND U_TEMPRESA.OUTROS='N' THEN 'C'
          WHEN  U_TEMPRESA.INSUMOS = 'S' THEN 'I'
           WHEN   U_TEMPRESA.GRAOS = 'S' THEN 'C'
           WHEN U_TEMPRESA.OUTROS='S' THEN 'O'
           ELSE 'O' END TPESTAB,
           
PREPRESE.REPRESENT || ' - ' || PREPRESE.DESCRICAO REPRESENTANTE,

COALESCE(PANALITI.DESCRICAO,'Duplicatas a Pagar') AS ANALITICA
    
FROM PDUPPAGA
 
 LEFT JOIN PREPRESE ON 
    PREPRESE.represent = PDUPPAGA.represent
    AND PREPRESE.empresa = PDUPPAGA.estabrepresent
 
  INNER JOIN CONTAMOV ON CONTAMOV.NUMEROCM = PDUPPAGA.FORNECEDOR
  
  LEFT JOIN PANALITI
    ON PANALITI.ANALITICA = PDUPPAGA.ANALITICA
    AND PANALITI.EMPRESA = PDUPPAGA.ESTABANALITICA
  
  INNER JOIN FILIAL ON FILIAL.ESTAB = PDUPPAGA.EMPRESA
  LEFT  join u_tempresa on u_tempresa.estab=filial.estab
  
  LEFT JOIN BAIXAS ON
    BAIXAS.EMPRESA = PDUPPAGA.EMPRESA
    AND BAIXAS.DUPPAG = PDUPPAGA.DUPPAG
    AND BAIXAS.FORNECEDOR = PDUPPAGA.FORNECEDOR
    
    LEFT JOIN PSITUACA
      ON PSITUACA.SITUACAO = PDUPPAGA.SITUACAO
      
    LEFT JOIN PANALITI
        ON PANALITI.ANALITICA = PDUPPAGA.ANALITICA
        AND PANALITI.EMPRESA = PDUPPAGA.ESTABANALITICA
    
    LEFT JOIN PPORTADO
      ON PPORTADO.PORTADOR = PDUPPAGA.PORTADOR
      AND PPORTADO.EMPRESA = PDUPPAGA.EMPRESA
      
     /* LEFT JOIN CENCUSCE
          ON CENCUSCE.cencuscod = PDUPPAGA.cencuscod
          AND CENCUSCE.centrocus = PDUPPAGA.centrocus*/
  

  WHERE  PDUPPAGA.DTENTRADA BETWEEN :DTINI AND :DTFIM
    AND (0 IN (:ESTAB) OR PDUPPAGA.EMPRESA IN (:ESTAB))
   -- AND ARREDONDAR(PDUPPAGA.VALOR - COALESCE(BAIXAS.VLR,0),0) >0
   AND ARREDONDAR(PDUPPAGA.VALOR - COALESCE(BAIXAS.PAGODPL,0),0) >0
    and PDUPPAGA.INCMANUT <> 'S'
    and FILIAL.EMPRESA IN (1,2,803,802,810,801)
    and FILIAL.EMPRESA IN (:EMPRESA)
  