WITH CHAVES_ADIANT AS (
    SELECT EMPRESA, ESTABFORNECEDOR, FORNECEDOR, DUPPAG, SEQPAGTODU FROM PPDUPPAD
    UNION
    SELECT EMPRESA, ESTABFORNECEDOR, FORNECEDOR, DUPPAG, SEQPAGTODU FROM PPADUCM
    UNION
    SELECT EMPRESA, ESTABFORNECEDOR, FORNECEDOR, DUPPAG, SEQPAGTODU FROM PPDUPPADUP
    UNION
    SELECT EMPRESA, ESTABFORNECEDOR, FORNECEDOR, DUPPAG, SEQPAGTODU FROM PPADUCHE
    UNION
    SELECT EMPRESA, ESTABFORNECEDOR, FORNECEDOR, DUPPAG, SEQPAGTODU FROM PPADUCHR
),
BAIXAS AS (
    SELECT /*+ NO_MERGE LEADING(K G) USE_HASH(G) FULL(G) */
        G.EMPRESA,
        G.DUPPAG,
        G.FORNECEDOR,
        MAX(G.DTPAGTO)                                            AS DTPAGTO,
        SUM(G.VALOR)                                              AS PAGO,
        SUM(CASE WHEN G.TIPOPAG = 'J' THEN G.VALOR ELSE 0 END)    AS JUROS,
        SUM(CASE WHEN G.TIPOPAG = 'P' THEN G.VALOR ELSE 0 END)    AS PAGODPL
    FROM CHAVES_ADIANT K
    INNER JOIN PPDUPPAG G
        ON  G.EMPRESA         = K.EMPRESA
        AND G.ESTABFORNECEDOR = K.ESTABFORNECEDOR
        AND G.FORNECEDOR      = K.FORNECEDOR
        AND G.DUPPAG          = K.DUPPAG
        AND G.SEQPAGTODU      = K.SEQPAGTODU
    WHERE G.TIPOPAG IN ('P','J')
    GROUP BY G.EMPRESA, G.DUPPAG, G.FORNECEDOR
)
SELECT /*+ GATHER_PLAN_STATISTICS */
    'Duplicatas a Pagar'                                   AS TIPO,
    'DPL-P'                                                AS TIPO_DOC,
    'PAGAR'                                                AS RECDESP,
    FILIAL.REDUZIDO                                        AS FILIAL,
    FILIAL.ESTAB,
    CONTAMOV.NOME                                          AS CLIENTE,
    CONTAMOV.NUMEROCM                                      AS NUMEROCM,
    PPORTADO.DESCRICAO                                     AS PORTADOR,
    PANALITI.DESCRICAO                                     AS TRANSACAO,
    PDUPPAGA.HISTORICO                                     AS HISTORICO,
    PDUPPAGA.DUPPAG                                        AS DOCUMENTO,
    (PDUPPAGA.VALOR - COALESCE(BAIXAS.PAGODPL,0))          AS SALDO,
    CASE WHEN COALESCE(BAIXAS.PAGODPL,0) = 0
         THEN 'ABERTA' ELSE 'PARCIALMENTE BAIXADA' END     AS STATUS,
    PDUPPAGA.VALOR                                         AS VALOR,
    COALESCE(BAIXAS.PAGO,0)                                AS VALORPAGO,
    COALESCE(BAIXAS.PAGODPL,0)                             AS VALOR_PAG_DPL,
    COALESCE(BAIXAS.JUROS,0)                               AS VALOR_JUROS,
    PDUPPAGA.DTEMISSAO                                     AS DTEMISSAO,
    PDUPPAGA.DTENTRADA                                     AS DTENTRADA,
    TO_CHAR(PDUPPAGA.DTVENCTO,'DD/MM/YYYY')                AS DTVENCTO,
    TO_CHAR(BAIXAS.DTPAGTO,'DD/MM/YYYY')                   AS DTPAGTO,
    PDUPPAGA.DTBASEJUROS                                   AS DTBASEJUROS,
    PDUPPAGA.DTVENCTO                                      AS DTJS,
    CASE WHEN U_TEMPRESA.INSUMOS = 'N' AND U_TEMPRESA.GRAOS = 'S' AND U_TEMPRESA.OUTROS = 'S' THEN 'O'
         WHEN U_TEMPRESA.INSUMOS = 'S' AND U_TEMPRESA.GRAOS = 'S' AND U_TEMPRESA.OUTROS = 'N' THEN 'C'
         WHEN U_TEMPRESA.INSUMOS = 'S' THEN 'I'
         WHEN U_TEMPRESA.GRAOS   = 'S' THEN 'C'
         WHEN U_TEMPRESA.OUTROS  = 'S' THEN 'O'
         ELSE 'O' END                                      AS TPESTAB,
    PREPRESE.REPRESENT || ' - ' || PREPRESE.DESCRICAO      AS REPRESENTANTE,
    COALESCE(PANALITI.DESCRICAO,'Duplicatas a Pagar')      AS ANALITICA
FROM PDUPPAGA
INNER JOIN FILIAL
    ON FILIAL.ESTAB = PDUPPAGA.EMPRESA
INNER JOIN CONTAMOV
    ON CONTAMOV.NUMEROCM = PDUPPAGA.FORNECEDOR
LEFT JOIN BAIXAS
    ON  BAIXAS.EMPRESA    = PDUPPAGA.EMPRESA
    AND BAIXAS.DUPPAG     = PDUPPAGA.DUPPAG
    AND BAIXAS.FORNECEDOR = PDUPPAGA.FORNECEDOR
LEFT JOIN U_TEMPRESA
    ON U_TEMPRESA.ESTAB = FILIAL.ESTAB
LEFT JOIN PREPRESE
    ON  PREPRESE.REPRESENT = PDUPPAGA.REPRESENT
    AND PREPRESE.EMPRESA   = PDUPPAGA.ESTABREPRESENT
LEFT JOIN PANALITI
    ON  PANALITI.ANALITICA = PDUPPAGA.ANALITICA
    AND PANALITI.EMPRESA   = PDUPPAGA.ESTABANALITICA
LEFT JOIN PPORTADO
    ON  PPORTADO.PORTADOR = PDUPPAGA.PORTADOR
    AND PPORTADO.EMPRESA  = PDUPPAGA.EMPRESA
WHERE PDUPPAGA.INCMANUT <> 'S'
  AND PDUPPAGA.QUITADA  = 'S'
  AND FILIAL.EMPRESA IN (1,2,801,802,803,810)
  AND CASE WHEN PDUPPAGA.VALOR - COALESCE(BAIXAS.PAGODPL,0) > 0
           THEN ARREDONDAR(PDUPPAGA.VALOR - COALESCE(BAIXAS.PAGODPL,0),0)
      END > 0;

