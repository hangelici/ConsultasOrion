WITH
/* filtro por mês: as datas informadas vão para o dia 1.
   DT_INI_ANT / DT_FIM_ANT = o mesmo período, 12 meses antes */
FILTRO AS (
SELECT
    TRUNC(CAST(:DTINI AS DATE), 'MM') AS DT_INI,
    TRUNC(CAST(:DTFIM AS DATE), 'MM') AS DT_FIM,
    ADD_MONTHS(TRUNC(CAST(:DTINI AS DATE), 'MM'), -12) AS DT_INI_ANT,
    ADD_MONTHS(TRUNC(CAST(:DTFIM AS DATE), 'MM'), -12) AS DT_FIM_ANT
FROM DUAL
),
/* REDUZIDAs que têm algum plano em U_PCC com NIVEL1 = 3 */
RED3 AS (
    SELECT DISTINCT P.REDUZIDA
      FROM U_PCC P
     WHERE P.NIVEL1 = 3
),
/* meses do calendário (de 01/2020 até hoje) dentro do período do filtro */
MESES AS (
    SELECT DISTINCT
           EXTRACT(MONTH FROM D.DDATA) AS MES,
           EXTRACT(YEAR  FROM D.DDATA) AS ANO
      FROM ALLDAYS(DATE '2020-01-01', CURRENT_DATE) D
     WHERE TO_DATE('01/'||EXTRACT(MONTH FROM D.DDATA)||'/'||EXTRACT(YEAR FROM D.DDATA), 'DD/MM/YYYY')
           BETWEEN (SELECT DT_INI FROM FILTRO) AND (SELECT DT_FIM FROM FILTRO)
        OR TO_DATE('01/'||EXTRACT(MONTH FROM D.DDATA)||'/'||EXTRACT(YEAR FROM D.DDATA), 'DD/MM/YYYY')
           BETWEEN (SELECT DT_INI_ANT FROM FILTRO) AND (SELECT DT_FIM_ANT FROM FILTRO)   -- 12 meses antes
),
/* combinações existentes na U_LANCF */
CONTAS AS (
    SELECT DISTINCT
           U.OSESTAB,
           U.OSPLANO,
           U.REDUZIDA,
           U.COD_CC,
           CE.CENTROPAI,
           CIDADE.UF,
           FILIAL.REDUZIDO AS FILIAL
      FROM VIASOFT.U_LANCF U
      INNER JOIN CENCUSCE CE ON
        CE.CENTROCUS = U.COD_CC
        AND CE.CENCUSCOD = 2
      INNER JOIN VIASOFT.FILIAL FILIAL ON FILIAL.ESTAB = TO_NUMBER(CE.CENTROPAI)
      INNER JOIN CIDADE ON CIDADE.CIDADE = FILIAL.CIDADE
     WHERE U.OSESTAB = 1
       AND U.REDUZIDA IN (SELECT REDUZIDA FROM RED3)
       AND FILIAL.ESTAB IN (:ESTAB)
       AND ('X' IN (:UF) OR CIDADE.UF IN (:UF))
),
/* meses SEM lançamento para cada combinação (mesma ordem de colunas da U_LANCF) */
FALTANTES AS (
    SELECT C.OSESTAB,
           C.OSPLANO,
           C.REDUZIDA,
           M.MES,
           M.ANO,
           C.COD_CC,
           NULL AS SALDO_INICIAL,
           NULL AS DEBITOS,
           NULL AS CREDITOS,
           NULL AS RDEBITOS,
           NULL AS RCREDITOS,
           C.CENTROPAI,
           C.UF,
           C.FILIAL
      FROM CONTAS C
     CROSS JOIN MESES M
     WHERE NOT EXISTS (SELECT 1
                         FROM VIASOFT.U_LANCF F
                        WHERE F.OSESTAB = C.OSESTAB
                          AND F.COD_CC  = C.COD_CC
                          AND F.REDUZIDA = C.REDUZIDA
                          AND F.ANO = M.ANO
                          AND F.MES = M.MES
                          AND F.OSESTAB = 1)
),
DRE AS (
    SELECT DISTINCT
    NIVEL1, 
    DESC1, 
    NIVEL2, 
    DESC2, 
    REDUZIDA
    FROM U_DRE
),
BASE AS (
SELECT
RESULTADO.*,
PCC.CONTA,
DRE.NIVEL1,
DRE.NIVEL2,
DRE.DESC1,
DRE.DESC2
FROM (

SELECT
OSESTAB,
OSPLANO,
COD_CC,
REDUZIDA,
ANO,
MES,
COALESCE(SALDO_INICIAL, 
    (LAG(SALDO_INICIAL IGNORE NULLS) OVER(PARTITION BY COD_CC,REDUZIDA ORDER BY ANO,MES))         
    -
    (LAG(CREDITOS IGNORE NULLS) OVER(PARTITION BY COD_CC,REDUZIDA ORDER BY ANO,MES)) 
    +
    (LAG(DEBITOS IGNORE NULLS) OVER(PARTITION BY COD_CC,REDUZIDA ORDER BY ANO,MES))
    -
    (LAG(RCREDITOS IGNORE NULLS) OVER(PARTITION BY COD_CC,REDUZIDA ORDER BY ANO,MES))
    +
    (LAG(RDEBITOS IGNORE NULLS) OVER(PARTITION BY COD_CC,REDUZIDA ORDER BY ANO,MES))
    
    )SALDO_INICIAL,
COALESCE(CREDITOS,0)CREDITOS,
COALESCE(DEBITOS,0)DEBITOS,
COALESCE(RCREDITOS,0)RCREDITOS,
COALESCE(RDEBITOS,0)RDEBITOS,
CAST(CURRENT_TIMESTAMP AS TIMESTAMP) AS DT_AT,
CENTROPAI,                                   -- vírgula que faltava
UF,
FILIAL

FROM(

SELECT
U_LANCF.*,
CE.CENTROPAI,
CIDADE.UF,
FILIAL.REDUZIDO AS FILIAL
FROM VIASOFT.U_LANCF U_LANCF 
INNER JOIN CENCUSCE CE ON
    CE.CENTROCUS = U_LANCF.COD_CC
    AND CE.CENCUSCOD = 2
INNER JOIN VIASOFT.FILIAL ON FILIAL.ESTAB = TO_NUMBER(CE.CENTROPAI)
INNER JOIN CIDADE ON CIDADE.CIDADE = FILIAL.CIDADE
WHERE U_LANCF.OSESTAB = 1
AND TO_DATE('01/'||U_LANCF.MES||'/'||U_LANCF.ANO, 'DD/MM/YYYY') <= (SELECT DT_FIM FROM FILTRO)
AND U_LANCF.REDUZIDA IN (SELECT REDUZIDA FROM RED3)
AND FILIAL.ESTAB IN (:ESTAB)
AND ('X' IN (:UF) OR CIDADE.UF IN (:UF))

UNION ALL

SELECT
*
FROM FALTANTES

)DADOS


UNION ALL

/* ---------- movimentos de SALCONCE (plano 1#1) ---------- */
SELECT
 1 AS OSESTAB,
    '1#1' AS OSPLANO,
    SALCONCE.CENTROCUS AS COD_CC,
    SALCONCE.ANALITICA AS REDUZIDA,
    SALCONCE.ANO, 
    SALCONCE.MES,
    0 AS SALDO_INICIAL,
    (CREDITOS) AS CREDITOS, 
    (DEBITOS) AS DEBITOS, 
    (RCREDITOS) AS RCREDITOS,
    (RDEBITOS) AS RDEBITOS,
    CAST(CURRENT_TIMESTAMP AS TIMESTAMP) AS DT_AT,
    CENCUSCE.CENTROPAI,
    CIDADE.UF,
    FILIAL.REDUZIDO AS FILIAL
FROM SALCONCE 

INNER JOIN CENCUSCE ON
    SALCONCE.CENTROCUS = CENCUSCE.CENTROCUS
INNER JOIN VIASOFT.FILIAL ON FILIAL.ESTAB = TO_NUMBER(CENCUSCE.CENTROPAI)     -- era CE (apelido inexistente aqui)
INNER JOIN CIDADE ON CIDADE.CIDADE = FILIAL.CIDADE

WHERE LENGTH(SALCONCE.CENTROCUS) = 9
AND  CENCUSCE.CENCUSCOD = 2
AND SALCONCE.ESTAB = 1
AND FILIAL.ESTAB IN (:ESTAB)                          -- era CE
AND ('X' IN (:UF) OR CIDADE.UF IN (:UF))
AND (    TO_DATE('01/'||SALCONCE.MES||'/'||SALCONCE.ANO, 'DD/MM/YYYY')
         BETWEEN (SELECT DT_INI FROM FILTRO) AND (SELECT DT_FIM FROM FILTRO)
      OR TO_DATE('01/'||SALCONCE.MES||'/'||SALCONCE.ANO, 'DD/MM/YYYY')
         BETWEEN (SELECT DT_INI_ANT FROM FILTRO) AND (SELECT DT_FIM_ANT FROM FILTRO))   -- 12 meses antes
AND EXISTS (SELECT 1 FROM U_PCC P
             WHERE P.OSPLANO = '1#1'
               AND P.REDUZIDA = SALCONCE.ANALITICA
               AND P.NIVEL1 = 3)

UNION ALL

/* ---------- saldos iniciais de U_SALDOC (plano 1#1) ---------- */
SELECT
 1 AS OSESTAB,
    '1#1' AS OSPLANO,
    U_SALDOC.CENTROCUS AS COD_CC,
    U_SALDOC.ANALITICA AS REDUZIDA,
    U_SALDOC.ANO, 
    U_SALDOC.MES,
    SALDOINI AS SALDO_INICIAL,
    0 AS CREDITOS, 
    0 AS DEBITOS, 
    0 AS RCREDITOS,
    0 AS RDEBITOS,
    CAST(CURRENT_TIMESTAMP AS TIMESTAMP) AS DT_AT,
    CENCUSCE.CENTROPAI,
    CIDADE.UF,
    FILIAL.REDUZIDO AS FILIAL
FROM U_SALDOC

INNER JOIN CENCUSCE ON
    U_SALDOC.CENTROCUS = CENCUSCE.CENTROCUS
INNER JOIN VIASOFT.FILIAL ON FILIAL.ESTAB = TO_NUMBER(CENCUSCE.CENTROPAI)     -- era CE
INNER JOIN CIDADE ON CIDADE.CIDADE = FILIAL.CIDADE

WHERE LENGTH(U_SALDOC.CENTROCUS) = 9
AND  CENCUSCE.CENCUSCOD = 2
AND FILIAL.ESTAB IN (:ESTAB)                          -- era CE
AND ('X' IN (:UF) OR CIDADE.UF IN (:UF))
AND (    TO_DATE('01/'||U_SALDOC.MES||'/'||U_SALDOC.ANO, 'DD/MM/YYYY')
         BETWEEN (SELECT DT_INI FROM FILTRO) AND (SELECT DT_FIM FROM FILTRO)
      OR TO_DATE('01/'||U_SALDOC.MES||'/'||U_SALDOC.ANO, 'DD/MM/YYYY')
         BETWEEN (SELECT DT_INI_ANT FROM FILTRO) AND (SELECT DT_FIM_ANT FROM FILTRO))   -- 12 meses antes
AND EXISTS (SELECT 1 FROM U_PCC P
             WHERE P.OSPLANO = '1#1'
               AND P.REDUZIDA = U_SALDOC.ANALITICA
               AND P.NIVEL1 = 3)
)
RESULTADO

INNER JOIN U_PCC PCC
    ON PCC.OSPLANO  = RESULTADO.OSPLANO
   AND PCC.REDUZIDA = RESULTADO.REDUZIDA
INNER JOIN U_PCC UDRE ON
    UDRE.REDUZIDA = PCC.DEPARA
    AND UDRE.OSPLANO = '0#1'
INNER JOIN DRE ON DRE.REDUZIDA = UDRE.REDUZIDA
WHERE PCC.NIVEL1 = 3
  AND (    TO_DATE('01/'||RESULTADO.MES||'/'||RESULTADO.ANO, 'DD/MM/YYYY')
           BETWEEN (SELECT DT_INI FROM FILTRO) AND (SELECT DT_FIM FROM FILTRO)
        OR TO_DATE('01/'||RESULTADO.MES||'/'||RESULTADO.ANO, 'DD/MM/YYYY')
           BETWEEN (SELECT DT_INI_ANT FROM FILTRO) AND (SELECT DT_FIM_ANT FROM FILTRO))   -- 12 meses antes
),
/* detalhe: MOVIMENTACAO por linha do DRE, conta, ano, mês e filial */
MOV AS (
    SELECT /*+ MATERIALIZE */
           D.ORDEM,
           D.DESC_CONTA,
           B.NIVEL1,
           B.DESC1,
           B.NIVEL2,
           B.DESC2,
           B.CONTA,
           B.ANO,
           B.MES,
           SUM(COALESCE(B.CREDITOS, 0) - COALESCE(B.DEBITOS, 0)) AS MOVIMENTACAO,
           B.CENTROPAI,
           B.UF,
           B.FILIAL
      FROM BASE B
     INNER JOIN U_DRECONSOLIDADO D
        ON D.NIVEL1   = B.NIVEL1
       AND D.SUBTOTAL = '0'
     GROUP BY D.ORDEM, D.DESC_CONTA, B.DESC1, B.DESC2, B.CONTA, B.ANO, B.MES, B.NIVEL1, B.NIVEL2,
              B.CENTROPAI, B.UF, B.FILIAL
),
/* total de cada linha de detalhe do DRE por ano, mês e filial */
NIVEIS AS (
    SELECT ORDEM, ANO, MES, CENTROPAI, UF, FILIAL,
           SUM(MOVIMENTACAO) AS MOVIMENTACAO
      FROM MOV
     GROUP BY ORDEM, ANO, MES, CENTROPAI, UF, FILIAL
),
/* combinações de ano, mês e filial que têm movimento */
PERIODOS AS (
    SELECT DISTINCT ANO, MES, CENTROPAI, UF, FILIAL
      FROM MOV
),
/* subtotais: soma das linhas de ORDEM anterior, por ano, mês e filial
   (DECODE compara tratando nulo = nulo) */
SUBTOTAIS AS (
    SELECT S.ORDEM,
           S.DESC_CONTA,
           P.ANO,
           P.MES,
           P.CENTROPAI,
           P.UF,
           P.FILIAL,
           NVL(SUM(N.MOVIMENTACAO), 0) AS MOVIMENTACAO
      FROM U_DRECONSOLIDADO S
     CROSS JOIN PERIODOS P
      LEFT JOIN NIVEIS N
        ON N.ANO = P.ANO
       AND N.MES = P.MES
       AND DECODE(N.CENTROPAI, P.CENTROPAI, 1, 0) = 1
       AND DECODE(N.UF,        P.UF,        1, 0) = 1
       AND DECODE(N.FILIAL,    P.FILIAL,    1, 0) = 1
       AND N.ORDEM < S.ORDEM
     WHERE S.SUBTOTAL = '1'
     GROUP BY S.ORDEM, S.DESC_CONTA, P.ANO, P.MES, P.CENTROPAI, P.UF, P.FILIAL
)
SELECT
       T.DESC_CONTA,
       T.DESC1,
       T.DESC2,
       T.CONTA,
       T.ANO,
       T.MES,
       T.MOVIMENTACAO,
       CASE
        WHEN T.MES = 1 THEN 'jan'
        WHEN T.MES = 2 THEN 'fev'
        WHEN T.MES = 3 THEN 'mar'
        WHEN T.MES = 4 THEN 'abr'
        WHEN T.MES = 5 THEN 'mai'
        WHEN T.MES = 6 THEN 'jun'
        WHEN T.MES = 7 THEN 'jul'
        WHEN T.MES = 8 THEN 'ago'
        WHEN T.MES = 9 THEN 'set'
        WHEN T.MES = 10 THEN 'out'
        WHEN T.MES = 11 THEN 'nov'
        WHEN T.MES = 12 THEN 'dez'
       END ||'/'||T.ANO AS MES_ANO,
       T.CENTROPAI,
       T.UF,
       T.FILIAL,
       /* 1 = período digitado; 0 = mesmo período, 12 meses antes */
       CASE
        WHEN TO_DATE('01/'||T.MES||'/'||T.ANO, 'DD/MM/YYYY')
             BETWEEN (SELECT DT_INI FROM FILTRO) AND (SELECT DT_FIM FROM FILTRO)
        THEN 1 ELSE 0
       END AS FILTRO
  FROM (
        SELECT ORDEM, DESC_CONTA, NIVEL1, DESC1, NIVEL2, DESC2, CONTA, ANO, MES, MOVIMENTACAO,
               CENTROPAI, UF, FILIAL
          FROM MOV
        UNION ALL
        SELECT ORDEM, DESC_CONTA, ORDEM, DESC_CONTA, ORDEM, DESC_CONTA, DESC_CONTA, ANO, MES, MOVIMENTACAO,
               CENTROPAI, UF, FILIAL
          FROM SUBTOTAIS
       ) T
 ORDER BY T.ANO, T.MES, T.CENTROPAI, T.ORDEM, T.NIVEL1, T.NIVEL2, T.CONTA