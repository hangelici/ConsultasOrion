WITH
/* filtro por mês: as datas informadas vão para o dia 1; nulo = sem limite */

FILTRO AS (
    
SELECT
    TRUNC(CAST(:DTINI AS DATE), 'MM') AS DT_INI,
    TRUNC(CAST(:DTFIM AS DATE), 'MM') AS DT_FIM
FROM DUAL

),
/* REDUZIDAs que têm algum plano em U_PCC com NIVEL1 = 3 (só pela REDUZIDA,
   chave de partição das janelas LAG: filtro seguro antes das janelas) */
RED3 AS (
    SELECT DISTINCT P.REDUZIDA
      FROM U_PCC P
     WHERE P.NIVEL1 = 3
),
/* meses do calendário (de 01/2020 até hoje) dentro do período do filtro
   (v6: limite inferior E superior; só alimentam FALTANTES, linhas nulas) */
MESES AS (
    SELECT DISTINCT
           EXTRACT(MONTH FROM D.DDATA) AS MES,
           EXTRACT(YEAR  FROM D.DDATA) AS ANO
      FROM ALLDAYS(DATE '2020-01-01', CURRENT_DATE) D
     WHERE TO_DATE('01/'||EXTRACT(MONTH FROM D.DDATA)||'/'||EXTRACT(YEAR FROM D.DDATA), 'DD/MM/YYYY')
           >= (SELECT DT_INI FROM FILTRO)
       AND TO_DATE('01/'||EXTRACT(MONTH FROM D.DDATA)||'/'||EXTRACT(YEAR FROM D.DDATA), 'DD/MM/YYYY')
           <= (SELECT DT_FIM FROM FILTRO)
),
/* combinações existentes na U_LANCF */
CONTAS AS (
    SELECT DISTINCT
           U.OSESTAB,
           U.OSPLANO,
           U.REDUZIDA,
           U.COD_CC,
           CE.CENTROPAI
      FROM VIASOFT.U_LANCF U
      INNER JOIN CENCUSCE CE ON
        CE.CENTROCUS = U.COD_CC
        AND CE.CENCUSCOD = 2
     WHERE U.OSESTAB = 1
       AND U.REDUZIDA IN (SELECT REDUZIDA FROM RED3)
       AND TO_NUMBER(CE.CENTROPAI) = :ESTAB
),
/* meses SEM lançamento para cada combinação (mesma ordem de colunas da U_LANCF) */
FALTANTES AS (
    SELECT C.OSESTAB,
           C.OSPLANO,
           C.REDUZIDA,
           M.MES,
           M.ANO,
           C.COD_CC,
           NULL AS SALDO_INICIAL,
           NULL AS DEBITOS,
           NULL AS CREDITOS,
           NULL AS RDEBITOS,
           NULL AS RCREDITOS,
           C.CENTROPAI
      FROM CONTAS C
     CROSS JOIN MESES M
     WHERE NOT EXISTS (SELECT 1
                         FROM VIASOFT.U_LANCF F
                        WHERE F.OSESTAB = C.OSESTAB
                          AND F.COD_CC  = C.COD_CC
                          AND F.REDUZIDA = C.REDUZIDA
                          AND F.ANO = M.ANO
                          AND F.MES = M.MES
                          AND F.OSESTAB = 1)
),
DRE AS (
    SELECT DISTINCT
    NIVEL1, 
    DESC1, 
    NIVEL2, 
    DESC2, 
    REDUZIDA
    FROM U_DRE
),
/* consulta v6 completa, sem alteração */
BASE AS (
SELECT
RESULTADO.*,
PCC.CONTA,
DRE.NIVEL1,
DRE.NIVEL2,
DRE.DESC1,
DRE.DESC2
FROM (

SELECT
OSESTAB,
OSPLANO,
COD_CC,
REDUZIDA,
ANO,
MES,
COALESCE(SALDO_INICIAL, 
    (LAG(SALDO_INICIAL IGNORE NULLS) OVER(PARTITION BY COD_CC,REDUZIDA ORDER BY ANO,MES))         
    -
    (LAG(CREDITOS IGNORE NULLS) OVER(PARTITION BY COD_CC,REDUZIDA ORDER BY ANO,MES)) 
    +
    (LAG(DEBITOS IGNORE NULLS) OVER(PARTITION BY COD_CC,REDUZIDA ORDER BY ANO,MES))
    -
    (LAG(RCREDITOS IGNORE NULLS) OVER(PARTITION BY COD_CC,REDUZIDA ORDER BY ANO,MES))
    +
    (LAG(RDEBITOS IGNORE NULLS) OVER(PARTITION BY COD_CC,REDUZIDA ORDER BY ANO,MES))
    
    )SALDO_INICIAL,
COALESCE(CREDITOS,0)CREDITOS,
COALESCE(DEBITOS,0)DEBITOS,
COALESCE(RCREDITOS,0)RCREDITOS,
COALESCE(RDEBITOS,0)RDEBITOS,
CAST(CURRENT_TIMESTAMP AS TIMESTAMP) AS DT_AT,
CENTROPAI

FROM(

SELECT
U_LANCF.*,
CE.CENTROPAI
FROM VIASOFT.U_LANCF U_LANCF 
INNER JOIN CENCUSCE CE ON
    CE.CENTROCUS = U_LANCF.COD_CC
    AND CE.CENCUSCOD = 2
WHERE U_LANCF.OSESTAB = 1
AND TO_DATE('01/'||U_LANCF.MES||'/'||U_LANCF.ANO, 'DD/MM/YYYY') <= (SELECT DT_FIM FROM FILTRO)
AND U_LANCF.REDUZIDA IN (SELECT REDUZIDA FROM RED3)
AND TO_NUMBER(CE.CENTROPAI) = :ESTAB

UNION ALL

SELECT
*
FROM FALTANTES

)DADOS


UNION ALL

/* ---------- v2: movimentos de SALCONCE (plano 1#1) ---------- */
SELECT
 1 AS OSESTAB,
    '1#1' AS OSPLANO,
    SALCONCE.CENTROCUS AS COD_CC,
    SALCONCE.ANALITICA AS REDUZIDA,
    SALCONCE.ANO, 
    SALCONCE.MES,
    0 AS SALDO_INICIAL,
    (CREDITOS) AS CREDITOS, 
    (DEBITOS) AS DEBITOS, 
    (RCREDITOS) AS RCREDITOS,
    (RDEBITOS) AS RDEBITOS,
    CAST(CURRENT_TIMESTAMP AS TIMESTAMP) AS DT_AT,
    CENCUSCE.CENTROPAI
FROM SALCONCE 

INNER JOIN CENCUSCE ON
    SALCONCE.CENTROCUS = CENCUSCE.CENTROCUS

WHERE LENGTH(SALCONCE.CENTROCUS) = 9
AND  CENCUSCE.CENCUSCOD = 2
AND SALCONCE.ESTAB = 1
AND TO_NUMBER(CENCUSCE.CENTROPAI) = :ESTAB
AND TO_DATE('01/'||SALCONCE.MES||'/'||SALCONCE.ANO, 'DD/MM/YYYY')
    BETWEEN (SELECT DT_INI FROM FILTRO) AND (SELECT DT_FIM FROM FILTRO)
AND EXISTS (SELECT 1 FROM U_PCC P
             WHERE P.OSPLANO = '1#1'
               AND P.REDUZIDA = SALCONCE.ANALITICA
               AND P.NIVEL1 = 3)

UNION ALL

/* ---------- v2: saldos iniciais de U_SALDOC (plano 1#1) ---------- */
SELECT
 1 AS OSESTAB,
    '1#1' AS OSPLANO,
    U_SALDOC.CENTROCUS AS COD_CC,
    U_SALDOC.ANALITICA AS REDUZIDA,
    U_SALDOC.ANO, 
    U_SALDOC.MES,
    SALDOINI AS SALDO_INICIAL,
    0 AS CREDITOS, 
    0 AS DEBITOS, 
    0 AS RCREDITOS,
    0 AS RDEBITOS,
    CAST(CURRENT_TIMESTAMP AS TIMESTAMP) AS DT_AT,
    CENCUSCE.CENTROPAI
FROM U_SALDOC

INNER JOIN CENCUSCE ON
    U_SALDOC.CENTROCUS = CENCUSCE.CENTROCUS

WHERE LENGTH(U_SALDOC.CENTROCUS) = 9
AND  CENCUSCE.CENCUSCOD = 2
AND TO_NUMBER(CENCUSCE.CENTROPAI) = :ESTAB
AND TO_DATE('01/'||U_SALDOC.MES||'/'||U_SALDOC.ANO, 'DD/MM/YYYY')
    BETWEEN (SELECT DT_INI FROM FILTRO) AND (SELECT DT_FIM FROM FILTRO)
AND EXISTS (SELECT 1 FROM U_PCC P
             WHERE P.OSPLANO = '1#1'
               AND P.REDUZIDA = U_SALDOC.ANALITICA
               AND P.NIVEL1 = 3)
)
RESULTADO

INNER JOIN U_PCC PCC
    ON PCC.OSPLANO  = RESULTADO.OSPLANO
   AND PCC.REDUZIDA = RESULTADO.REDUZIDA
INNER JOIN U_PCC UDRE ON
    UDRE.REDUZIDA = PCC.DEPARA
    AND UDRE.OSPLANO = '0#1'
INNER JOIN DRE ON DRE.REDUZIDA = UDRE.REDUZIDA
WHERE PCC.NIVEL1 = 3
  AND TO_DATE('01/'||RESULTADO.MES||'/'||RESULTADO.ANO, 'DD/MM/YYYY')
      BETWEEN (SELECT DT_INI FROM FILTRO) AND (SELECT DT_FIM FROM FILTRO)
),
/* detalhe: MOVIMENTACAO por linha do DRE, conta, ano e mês */
MOV AS (
    SELECT /*+ MATERIALIZE */
           D.ORDEM,
           D.DESC_CONTA,
           B.NIVEL1,
           B.DESC1,
           B.NIVEL2,
           B.DESC2,
           B.CONTA,
           B.ANO,
           B.MES,
           SUM(COALESCE(B.CREDITOS, 0) - COALESCE(B.DEBITOS, 0)) AS MOVIMENTACAO
      FROM BASE B
     INNER JOIN U_DRECONSOLIDADO D
        ON D.NIVEL1   = B.NIVEL1
       AND D.SUBTOTAL = '0'
     GROUP BY D.ORDEM, D.DESC_CONTA, B.DESC1, B.DESC2, B.CONTA, B.ANO, B.MES, B.NIVEL1, B.NIVEL2
),
NIVEIS AS (
    SELECT ORDEM, ANO, MES, SUM(MOVIMENTACAO) AS MOVIMENTACAO
      FROM MOV
     GROUP BY ORDEM, ANO, MES
),
PERIODOS AS (
    SELECT DISTINCT ANO, MES FROM MOV
),
/* subtotais: soma acumulada dos níveis de ORDEM anterior, por ano e mês */
SUBTOTAIS AS (
    SELECT S.ORDEM,
           S.DESC_CONTA,
           P.ANO,
           P.MES,
           NVL((SELECT SUM(N.MOVIMENTACAO)
                  FROM NIVEIS N
                 WHERE N.ANO = P.ANO
                   AND N.MES = P.MES
                   AND N.ORDEM < S.ORDEM), 0) AS MOVIMENTACAO
      FROM U_DRECONSOLIDADO S
     CROSS JOIN PERIODOS P
     WHERE S.SUBTOTAL = '1'
)
SELECT
       T.DESC_CONTA,
       T.DESC1,
       T.DESC2,
       T.CONTA,
       T.ANO,
       T.MES,
       T.MOVIMENTACAO,
       CASE
        WHEN MES = 1 THEN 'jan'
        WHEN MES = 2 THEN 'fev'
        WHEN MES = 3 THEN 'mar'
        WHEN MES = 4 THEN 'abr'
        WHEN MES = 5 THEN 'mai'
        WHEN MES = 6 THEN 'jun'
        WHEN MES = 7 THEN 'jul'
        WHEN MES = 8 THEN 'ago'
        WHEN MES = 9 THEN 'set'
        WHEN MES = 10 THEN 'out'
        WHEN MES = 11 THEN 'nov'
        WHEN MES = 12 THEN 'dez'
    END ||'/'||ANO AS MES_ANO
  FROM (
        SELECT ORDEM, DESC_CONTA, NIVEL1, DESC1, NIVEL2, DESC2, CONTA, ANO, MES, MOVIMENTACAO
          FROM MOV
        UNION ALL
        SELECT ORDEM, DESC_CONTA, ORDEM, DESC_CONTA, ORDEM, DESC_CONTA, DESC_CONTA, ANO, MES, MOVIMENTACAO
          FROM SUBTOTAIS
       ) T
 ORDER BY T.ANO, T.MES, T.ORDEM, T.NIVEL1, T.NIVEL2, T.CONTA