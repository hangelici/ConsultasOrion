WITH 
CTRNOTA AS (
    SELECT
    CONTRATONFITE.ESTAB,
    CONTRATONFITE.CONTRATO,
    CONTRATONFITE.SEQITEM,
    CASE 
        WHEN (NAT.TIPODCTO IN ('N','X','A','T') and NFCFG.NOTACONF not IN (1041)) AND NATAPARTIRDE.TIPOBAIXA IN ('A','Q') AND NFCAB.NOTACONF NOT IN (291) AND NATAPARTIRDE.OPERACAO NOT IN ('N','R') THEN CONTRATONFITE.QUANTIDADE
        WHEN NAT.TIPODCTO IN ('D') AND NATAPARTIRDE.TIPOBAIXA IN ('A','Q') AND NAT.ENTRADASAIDA = 'E' AND CONTRATOCFG.ENTRADASAIDA = 'E' AND NATAPARTIRDE.OPERACAO NOT IN ('N','R') THEN CONTRATONFITE.QUANTIDADE
        WHEN NAT.TIPODCTO IN ('D') AND NATAPARTIRDE.TIPOBAIXA IN ('A','Q') AND NAT.ENTRADASAIDA = 'S' AND CONTRATOCFG.ENTRADASAIDA = 'S' AND NATAPARTIRDE.OPERACAO NOT IN ('N','R') THEN CONTRATONFITE.QUANTIDADE
        ELSE 0
    END BAIXADO,
    CASE 
        WHEN NAT.TIPODCTO IN ('D') AND NATAPARTIRDE.TIPOBAIXA IN ('A','Q') AND NAT.ENTRADASAIDA = 'E' AND CONTRATOCFG.ENTRADASAIDA = 'E' AND NATAPARTIRDE.OPERACAO NOT IN ('N','R') THEN 0
        WHEN NAT.TIPODCTO IN ('D') AND NATAPARTIRDE.TIPOBAIXA IN ('A','Q') AND NAT.ENTRADASAIDA = 'S' AND CONTRATOCFG.ENTRADASAIDA = 'S' AND NATAPARTIRDE.OPERACAO NOT IN ('N','R') THEN 0
        WHEN (NAT.TIPODCTO = 'D' OR NFCFG.NOTACONF IN (1041)) AND NATAPARTIRDE.TIPOBAIXA IN ('A','Q') AND NATAPARTIRDE.OPERACAO NOT IN ('N','R') THEN CONTRATONFITE.QUANTIDADE
        ELSE 0
    END DEVOLIDO,
    CASE 
        WHEN NAT.TIPODCTO IN ('N','X','A') AND NATAPARTIRDE.TIPOBAIXA IN ('A','Q') AND NFCFG.NOTACONF IN (291) AND NATAPARTIRDE.OPERACAO NOT IN ('N','R') THEN CONTRATONFITE.QUANTIDADE
        ELSE 0
    END CANCELADO
    FROM CONTRATONFITE
    INNER JOIN CONTRATO ON CONTRATO.ESTAB = CONTRATONFITE.ESTAB AND CONTRATO.CONTRATO = CONTRATONFITE.CONTRATO
    INNER JOIN CONTRATOITE ON 
        CONTRATOITE.ESTAB = CONTRATONFITE.ESTAB
        AND CONTRATOITE.CONTRATO = CONTRATONFITE.CONTRATO
        AND CONTRATONFITE.SEQITEM = CONTRATONFITE.SEQITEM
    INNER JOIN NFCAB ON NFCAB.ESTAB = CONTRATONFITE.ESTABNOTA AND NFCAB.SEQNOTA = CONTRATONFITE.SEQNOTA
    INNER JOIN NFCFG ON NFCFG.NOTACONF = NFCAB.NOTACONF
    INNER JOIN NATOPERACAO NAT ON NAT.NATUREZADAOPERACAO = NFCFG.NATUREZADAOPERACAO AND NAT.ENTRADASAIDA = NFCFG.ENTRADASAIDA 
    INNER JOIN CONTRATOCFG ON CONTRATOCFG.CONTCONF = CONTRATO.CONTCONF    
    INNER JOIN CONTRATOCFG_U ON CONTRATOCFG_U.CONTCONF = CONTRATO.CONTCONF
    LEFT JOIN U_TIPOCTR ON U_TIPOCTR.U_TIPOCTR_ID = CONTRATOCFG_U.U_TIPOCTR_ID  
    LEFT JOIN NFCFG_U U ON U.NOTACONF = NFCFG.NOTACONF
    LEFT JOIN U_TIPOOP P ON U.U_TIPOOP_ID = P.U_TIPOOP_ID
    LEFT JOIN NATAPARTIRDE ON
        NATAPARTIRDE.NATUREZADAOPERACAO = NAT.NATUREZADAOPERACAO
        AND NATAPARTIRDE.ENTRADASAIDA = NAT.ENTRADASAIDA
        AND NATAPARTIRDE.NATOPERORIGEM = CONTRATOCFG.NATUREZA
        AND NATAPARTIRDE.ENTRADASAIDAORIGEM = CONTRATOCFG.ENTRADASAIDA
    WHERE CONTRATOCFG.ENTRADASAIDA IN ('E','S')
),
BAIXAS AS (
    SELECT
    ESTAB,
    CONTRATO,
    SEQITEM,
    SUM(BAIXADO) AS BAIXADO,
    SUM(DEVOLIDO) AS DEVOLIDO,
    SUM(CANCELADO) AS CANCELADO
    FROM CTRNOTA
    GROUP BY ESTAB, CONTRATO, SEQITEM
),
CANC AS (
    SELECT
    CONTRATOCANC.ESTAB,
    CONTRATOCANC.CONTRATO,
    CONTRATOCANC.SEQITEM,
    SUM(CONTRATOCANC.QUANTIDADE) AS CANC
    FROM CONTRATOCANC
    INNER JOIN CONTRATO ON CONTRATO.ESTAB = CONTRATOCANC.ESTAB AND CONTRATO.CONTRATO = CONTRATOCANC.CONTRATO
    INNER JOIN CONTRATOCFG ON CONTRATOCFG.CONTCONF = CONTRATO.CONTCONF    
    INNER JOIN CONTRATOCFG_U ON CONTRATOCFG_U.CONTCONF = CONTRATO.CONTCONF
    LEFT JOIN U_TIPOCTR ON U_TIPOCTR.U_TIPOCTR_ID = CONTRATOCFG_U.U_TIPOCTR_ID 
    WHERE CONTRATOCFG.ENTRADASAIDA IN ('E','S')
    GROUP BY CONTRATOCANC.ESTAB, CONTRATOCANC.CONTRATO, CONTRATOCANC.SEQITEM
),
-- AJUSTE: SEQITEM adicionado para o join ficar no grao certo de item de contrato
SALDO_MANUAL AS (
SELECT 
    CONTRATO.ESTAB,
    CONTRATO.CONTRATO,
    CONTRATOITE.SEQITEM,
    U_AGRPRODGR.U_AGRPRODGR_ID AS ITEM,
    LOCALEST.LOCAL,
    ARREDONDAR(CONTRATOITE.QUANTIDADE - NVL(BAIXAS.BAIXADO,0) - NVL(BAIXAS.CANCELADO,0) + NVL(BAIXAS.DEVOLIDO,0) - NVL(CANC.CANC,0), 0) QTDSALDO
FROM CONTRATO
INNER JOIN CONTRATOCFG ON CONTRATOCFG.CONTCONF = CONTRATO.CONTCONF
INNER JOIN CONTRATOCFG_U ON CONTRATOCFG_U.CONTCONF = CONTRATO.CONTCONF
LEFT JOIN U_TIPOCTR ON U_TIPOCTR.U_TIPOCTR_ID = CONTRATOCFG_U.U_TIPOCTR_ID
INNER JOIN U_TEMPRESA U ON U.ESTAB = CONTRATO.ESTAB
LEFT JOIN ENDERECO ON
    ENDERECO.NUMEROCM = CONTRATO.NUMEROCM
    AND ENDERECO.SEQENDERECO =  CONTRATO.ENDALTERNATIVO
INNER JOIN CONTAMOV ON CONTAMOV.NUMEROCM = CONTRATO.NUMEROCM
LEFT JOIN FILIAL ON FILIAL.ESTAB = CONTRATO.ESTAB
INNER JOIN CIDADE ON CIDADE.CIDADE = FILIAL.CIDADE
LEFT JOIN CONTRATOITE ON 
    CONTRATOITE.ESTAB = CONTRATO.ESTAB 
    AND CONTRATOITE.CONTRATO = CONTRATO.CONTRATO
LEFT JOIN LOCALEST ON 
    LOCALEST.ESTAB = CONTRATOITE.ESTAB
    AND LOCALEST.LOCAL = CONTRATOITE.LOCAL
LEFT JOIN BAIXAS ON 
    BAIXAS.ESTAB = CONTRATOITE.ESTAB 
    AND BAIXAS.CONTRATO = CONTRATOITE.CONTRATO 
    AND BAIXAS.SEQITEM = CONTRATOITE.SEQITEM
LEFT JOIN CANC ON 
    CANC.ESTAB = CONTRATOITE.ESTAB 
    AND CANC.CONTRATO = CONTRATOITE.CONTRATO 
    AND CANC.SEQITEM = CONTRATOITE.SEQITEM
LEFT JOIN ITEMAGRO ON ITEMAGRO.ITEM = CONTRATOITE.ITEM
LEFT JOIN ITEMAGRO_U ON ITEMAGRO_U.ITEM = ITEMAGRO.ITEM
LEFT JOIN U_AGRPRODGR ON U_AGRPRODGR.U_AGRPRODGR_ID = ITEMAGRO_U.U_AGRPRODGR_ID
WHERE 
CONTRATOCFG.ENTRADASAIDA IN ('E','S')
AND U.GRAOS='S'
AND FILIAL.INATIVA = 'N'
AND ARREDONDAR(CONTRATOITE.QUANTIDADE - COALESCE(BAIXAS.BAIXADO,0) - COALESCE(BAIXAS.CANCELADO,0) + COALESCE(BAIXAS.DEVOLIDO,0) - COALESCE(CANC.CANC,0), 0) > 0
),
-- ==========================================================
-- A PARTIR DAQUI, ESTRUTURA ORIGINAL DA QUERY, SEM ALTERACAO (exceto CONTRATOS abaixo)
-- ==========================================================
NOTAS AS (
    SELECT
    *
    FROM(
    
    SELECT
    UF,
    UFNOME,
    ITEM,
    CIDENTREGA,
    SUM(SALDONOTA) AS SALDOTOTAL
    FROM(

    SELECT
    CASE WHEN TRADING = 'S' THEN 'TR' ELSE UF.UF END UF,
    CASE WHEN TRADING = 'S' THEN 'Trading' ELSE UF.NOME END UFNOME,
    U_AGRPRODGR.U_AGRPRODGR_ID AS ITEM,
      CASE 
        WHEN NFCAB.NOTACONF = 388 THEN CID_388.NOME
        WHEN NFCAB.NOTACONF in (394,1388) THEN CID_394.NOME
        ELSE CID_PADRAO.NOME
    END AS CIDENTREGA,
     
    NFCAB.NOTA,
    SUM(NFITEM.QUANTIDADE) AS QTDNOTA,
    -- CÁLCULO CORRIGIDO - VERSÃO FINAL
    SUM(NFITEM.QUANTIDADE) - 
    SUM(COALESCE((
        SELECT SUM(B.QUANTIDADE) 
        FROM NFITEMAPARTIRDE B 
        WHERE B.ESTABORIGEM = NFCAB.ESTAB 
        AND B.SEQNOTAORIGEM = NFCAB.SEQNOTA 
        AND B.SEQNOTAITEMORIGEM = NFITEM.SEQNOTAITEM
    ), 0)) AS SALDONOTA
    FROM NFCAB
    
    INNER JOIN NFITEM ON
        NFITEM.ESTAB = NFCAB.ESTAB
        AND NFITEM.SEQNOTA = NFCAB.SEQNOTA
        
    LEFT JOIN CONTRATO ON
        CONTRATO.ESTAB = NFITEM.ESTAB AND
        CONTRATO.CONTRATO = NFITEM.CONTRATO AND
        NFCAB.NOTACONF in (394,1388)
        
    INNER JOIN FILIAL ON FILIAL.ESTAB = NFCAB.ESTAB
    INNER JOIN U_TEMPRESA ON U_TEMPRESA.ESTAB = FILIAL.ESTAB
    INNER JOIN CIDADE ON CIDADE.CIDADE = FILIAL.CIDADE
    INNER JOIN UF ON UF.UF = CIDADE.UF
    
    INNER JOIN ITEMAGRO ON ITEMAGRO.ITEM = NFITEM.ITEM
    INNER JOIN ITEMAGRO_U ON ITEMAGRO_U.ITEM = ITEMAGRO.ITEM
    INNER JOIN U_AGRPRODGR ON U_AGRPRODGR.U_AGRPRODGR_ID = ITEMAGRO_U.U_AGRPRODGR_ID
  
  LEFT JOIN CONTAMOV MOV ON MOV.NUMEROCM = NFCAB.PESSENTREGA

LEFT JOIN ENDERECO ON
    ENDERECO.NUMEROCM = NFCAB.PESSENTREGA
    AND ENDERECO.SEQENDERECO = NFCAB.SEQENDENTREGA

LEFT JOIN CIDADE CID_PADRAO 
    ON CID_PADRAO.CIDADE = COALESCE(ENDERECO.CIDADE, MOV.CIDADE)

-- 388 → ORDEM DE CARGA
LEFT JOIN ORDEMCARGAFRETE OCF 
    ON OCF.IDCARGA = NFCAB.ORDEMCARGA
    AND OCF.ESTAB = NFCAB.ESTAB
    AND NFCAB.NOTACONF = 388

LEFT JOIN LOCALEST LOC_EST 
    ON LOC_EST.ESTAB = OCF.ESTAB
    AND LOC_EST.LOCAL = OCF.LOCALESTOQUE

LEFT JOIN LOCALEST_U LOC_EST_U 
    ON LOC_EST_U.ESTAB = LOC_EST.ESTAB
    AND LOC_EST_U.LOCAL = LOC_EST.LOCAL

LEFT JOIN CIDADE CID_388 
    ON CID_388.CIDADE = LOC_EST_U.CIDADEPESSOA

-- 394 → CONTRATO
LEFT JOIN CONTRATO CTR 
    ON CTR.ESTAB = NFITEM.ESTAB 
    AND CTR.CONTRATO = NFITEM.CONTRATO
    AND NFCAB.NOTACONF in (394,1388)

LEFT JOIN (
    SELECT 
        ESTAB,
        CONTRATO,
        MIN(LOCAL) AS LOCAL
    FROM CONTRATOITE
    GROUP BY ESTAB, CONTRATO
) CTRI 
    ON CTRI.ESTAB = CTR.ESTAB 
    AND CTRI.CONTRATO = CTR.CONTRATO

LEFT JOIN LOCALEST LOC_CTR 
    ON LOC_CTR.ESTAB = CTRI.ESTAB 
    AND LOC_CTR.LOCAL = CTRI.LOCAL

LEFT JOIN LOCALEST_U LOC_CTR_U 
    ON LOC_CTR_U.ESTAB = LOC_CTR.ESTAB 
    AND LOC_CTR_U.LOCAL = LOC_CTR.LOCAL

LEFT JOIN CIDADE CID_394 
    ON CID_394.CIDADE = LOC_CTR_U.CIDADEPESSOA
    
  
    WHERE
    NFCAB.NOTACONF IN (388,394,382,1388)
    AND COALESCE(NFCAB.STATUS,'X') <> 'C'
    AND (
        'X' IN (:UF)
        OR
        (CASE WHEN TRADING = 'S' THEN 'TR' ELSE UF.UF END) IN (:UF)
        )
      AND U_AGRPRODGR.U_AGRPRODGR_ID = :ITEM

    GROUP BY
    TRADING,
    NFCAB.NOTA,
    UF.UF,
    UF.NOME,
    U_AGRPRODGR.U_AGRPRODGR_ID,
    CASE
        WHEN NFCAB.NOTACONF = 388 THEN CID_388.NOME
        WHEN NFCAB.NOTACONF IN (394,1388) THEN CID_394.NOME
        ELSE CID_PADRAO.NOME
    END

    )DADOS

    GROUP BY
    UF,
    UFNOME,
    ITEM,
    CIDENTREGA
    
    )DADOS1
   WHERE SALDOTOTAL <> 0
    
),

CONTRATOS AS (
  SELECT
  *
  FROM(
    SELECT
    CASE
    WHEN CONTCONF = 7
         AND CONTRATO_U.TIPOFRETES = 'CIF'
    THEN CIDPESS.NOME
    ELSE COALESCE(CIDPESS.NOME,CID.NOME)
END AS CIDENTREGA,
    CASE WHEN TRADING = 'S' THEN 'TR' ELSE UF.UF END UF,
    CASE WHEN TRADING = 'S' THEN 'Trading' ELSE UF.NOME END UFNOME,
    U_AGRPRODGR.U_AGRPRODGR_ID AS ITEM,
    SUM(
        CASE WHEN CONTRATO.CONTCONF = 26 then ARREDONDAR(COALESCE(SM.QTDSALDO,0),2) ELSE 0 END
        ) AS QTDCTR,
      SUM(
        CASE WHEN CONTRATO.CONTCONF = 7 AND CONTRATO_U.TIPOFRETES = 'CIF' then ARREDONDAR(COALESCE(SM.QTDSALDO,0),2) ELSE 0 END
        ) AS QTDCTR_C,
    SUM(
        CASE WHEN CONTRATO.CONTCONF = 38 then ARREDONDAR(COALESCE(SM.QTDSALDO,0),2) ELSE 0 END
        ) AS QTD_AFIXAR
    FROM CONTRATO
    
    INNER JOIN CONTRATOITE ON
        CONTRATOITE.ESTAB = CONTRATO.ESTAB
        AND CONTRATOITE.CONTRATO = CONTRATO.CONTRATO
        
    INNER JOIN FILIAL ON FILIAL.ESTAB = CONTRATO.ESTAB
    INNER JOIN U_TEMPRESA ON U_TEMPRESA.ESTAB = FILIAL.ESTAB
    INNER JOIN CIDADE ON CIDADE.CIDADE = FILIAL.CIDADE
    INNER JOIN UF ON UF.UF = CIDADE.UF
    
    INNER JOIN ITEMAGRO ON ITEMAGRO.ITEM = CONTRATOITE.ITEM
    INNER JOIN ITEMAGRO_U ON ITEMAGRO_U.ITEM = ITEMAGRO.ITEM
    INNER JOIN U_AGRPRODGR ON U_AGRPRODGR.U_AGRPRODGR_ID = ITEMAGRO_U.U_AGRPRODGR_ID
    
    LEFT JOIN (
        SELECT
        ESTAB,
        CONTRATO,
        SEQITEM,
        SUM(QUANTIDADE) AS QTDCANC
        FROM CONTRATOCANC
        GROUP BY
        ESTAB,CONTRATO,SEQITEM
    )CANCELADO ON
    CANCELADO.ESTAB = CONTRATOITE.ESTAB
    AND CANCELADO.CONTRATO = CONTRATOITE.CONTRATO
    AND CANCELADO.SEQITEM = CONTRATOITE.SEQITEM
    
    LEFT JOIN CONTAMOV ON CONTAMOV.NUMEROCM = CONTRATO.PESSENTREGA
    LEFT JOIN ENDERECO ON 
        ENDERECO.NUMEROCM = CONTRATO.PESSENTREGA
        AND ENDERECO.SEQENDERECO = CONTRATO.SEQENDENTREGA
    
    LEFT JOIN CIDADE CID ON CID.CIDADE = COALESCE(ENDERECO.CIDADE,CONTAMOV.CIDADE)
    
    -- AJUSTE: PCONTRATOSALDO substituida por SALDO_MANUAL, join por ESTAB+CONTRATO+SEQITEM
    LEFT JOIN SALDO_MANUAL SM
        ON  SM.ESTAB    = CONTRATO.ESTAB
        AND SM.CONTRATO = CONTRATO.CONTRATO
        AND SM.SEQITEM  = CONTRATOITE.SEQITEM
  
    LEFT JOIN CONTRATO_U ON
        CONTRATO_U.ESTAB = CONTRATO.ESTAB
        AND CONTRATO_U.CONTRATO = CONTRATO.CONTRATO

    LEFT JOIN LOCALEST ON 
        LOCALEST.ESTAB = CONTRATOITE.ESTAB
        AND LOCALEST.LOCAL = CONTRATOITE.LOCAL
        
    LEFT JOIN LOCALEST_U ON
       LOCALEST.ESTAB = LOCALEST_U.ESTAB
        AND LOCALEST.LOCAL = LOCALEST_U.LOCAL 
        
    LEFT JOIN CIDADE CIDPESS ON CIDPESS.CIDADE = LOCALEST_U.CIDADEPESSOA
    
    WHERE
    CONTRATO.CONTCONF  in (26,7,38,8)
    AND CONTRATO.DTLIMENTIMP BETWEEN :DTINI AND :DTFIM
    and ARREDONDAR(COALESCE(SM.QTDSALDO,0),2) > 0
   AND (
        'X' IN (:UF)
        OR
        (CASE WHEN TRADING = 'S' THEN 'TR' ELSE UF.UF END) IN (:UF)
        )
    AND U_AGRPRODGR.U_AGRPRODGR_ID = :ITEM
    
    GROUP BY
    TRADING,
    UF.UF,
    UF.NOME ,
    CID.NOME,
    CIDPESS.NOME,
    CONTCONF,
    CONTRATO_U.TIPOFRETES,
    U_AGRPRODGR.U_AGRPRODGR_ID
    )DADOS WHERE QTDCTR <> 0 OR QTDCTR_C <> 0 or QTD_AFIXAR <> 0
),

RETENCAO AS (
   SELECT
    CASE WHEN TRADING = 'S' THEN 'TR' ELSE UF.UF END AS UF,
    CASE WHEN TRADING = 'S' THEN 'Trading' ELSE UF.NOME END AS UFNOME,
    U_AGRPRODGR.U_AGRPRODGR_ID AS ITEM,
        CASE 
        WHEN NFCAB.NOTACONF = 388 THEN CID_388.NOME
        WHEN NFCAB.NOTACONF in (394,1388) THEN CID_394.NOME
        ELSE CID_PADRAO.NOME
    END AS CIDENTREGA,
    
    R.PESORETENCAO,
    ARREDONDAR(DIVIDE(R.PESORETENCAO,60),2) AS PESORETENCAO_SC

    FROM RETENPORTO R

    INNER JOIN NFCAB ON
        NFCAB.ESTAB = R.ESTAB
        AND NFCAB.SEQNOTA = R.SEQNOTA
        AND NFCAB.NUMEROCM = R.NUMEROCM

    -- CORREÇÃO CRÍTICA: buscar contrato via NFITEM
    LEFT JOIN NFITEM NI ON
        NI.ESTAB = R.ESTAB
        AND NI.SEQNOTA = R.SEQNOTA
        AND NI.SEQNOTAITEM = R.SEQNOTAITEM

    -- ENDEREÇO PADRÃO
    LEFT JOIN ENDERECO ON
        ENDERECO.NUMEROCM = NFCAB.PESSENTREGA
        AND ENDERECO.SEQENDERECO = NFCAB.SEQENDENTREGA

    LEFT JOIN CONTAMOV ON CONTAMOV.NUMEROCM = NFCAB.PESSENTREGA

    LEFT JOIN CIDADE CID_PADRAO 
        ON CID_PADRAO.CIDADE = COALESCE(ENDERECO.CIDADE, CONTAMOV.CIDADE)

    -- ESTRUTURA EMPRESA
    INNER JOIN FILIAL ON FILIAL.ESTAB = NFCAB.ESTAB
    INNER JOIN U_TEMPRESA ON U_TEMPRESA.ESTAB = FILIAL.ESTAB
    INNER JOIN CIDADE ON CIDADE.CIDADE = FILIAL.CIDADE
    INNER JOIN UF ON UF.UF = CIDADE.UF 

    -- ITEM
    INNER JOIN ITEMAGRO ON ITEMAGRO.ITEM = R.ITEM
    INNER JOIN ITEMAGRO_U ON ITEMAGRO_U.ITEM = ITEMAGRO.ITEM
    INNER JOIN U_AGRPRODGR ON U_AGRPRODGR.U_AGRPRODGR_ID = ITEMAGRO_U.U_AGRPRODGR_ID

    -- CONTROLE RETENÇÃO
    LEFT JOIN RETENPORTO_U ON 
        RETENPORTO_U.ESTAB = R.ESTAB
        AND RETENPORTO_U.SEQNOTA = R.SEQNOTA
        AND RETENPORTO_U.NUMEROCM = R.NUMEROCM
        AND RETENPORTO_U.SEQNOTAITEM = R.SEQNOTAITEM

    -- =========================
    -- 388 → ORDEM DE CARGA
    -- =========================
    LEFT JOIN ORDEMCARGAFRETE OCF 
        ON OCF.IDCARGA = NFCAB.ORDEMCARGA
        AND OCF.ESTAB = NFCAB.ESTAB
        AND NFCAB.NOTACONF = 388

    LEFT JOIN LOCALEST LOC_EST 
        ON LOC_EST.ESTAB = OCF.ESTAB
        AND LOC_EST.LOCAL = OCF.LOCALESTOQUE

    LEFT JOIN LOCALEST_U LOC_EST_U 
        ON LOC_EST_U.ESTAB = LOC_EST.ESTAB
        AND LOC_EST_U.LOCAL = LOC_EST.LOCAL

    LEFT JOIN CIDADE CID_388 
        ON CID_388.CIDADE = LOC_EST_U.CIDADEPESSOA    


    -- 394 CONTRATO (CORRIGIDO)

    LEFT JOIN CONTRATO CTR 
        ON CTR.ESTAB = NI.ESTAB 
        AND CTR.CONTRATO = NI.CONTRATO
        AND NFCAB.NOTACONF in (394,1388)

    LEFT JOIN (
        SELECT 
            ESTAB,
            CONTRATO,
            MIN(LOCAL) AS LOCAL
        FROM CONTRATOITE
        GROUP BY ESTAB, CONTRATO
    ) CTRI 
        ON CTRI.ESTAB = CTR.ESTAB 
        AND CTRI.CONTRATO = CTR.CONTRATO

    LEFT JOIN LOCALEST LOC_CTR 
        ON LOC_CTR.ESTAB = CTRI.ESTAB 
        AND LOC_CTR.LOCAL = CTRI.LOCAL

    LEFT JOIN LOCALEST_U LOC_CTR_U 
        ON LOC_CTR_U.ESTAB = LOC_CTR.ESTAB 
        AND LOC_CTR_U.LOCAL = LOC_CTR.LOCAL

    LEFT JOIN CIDADE CID_394 
        ON CID_394.CIDADE = LOC_CTR_U.CIDADEPESSOA        

    -- FILTROS
    WHERE 
        R.TRANSACAO = 'E'
        AND NFCAB.NOTACONF IN (394,382,388,1388)
        AND R.PESORETENCAO <> 0
        AND R.DTRETENCAO BETWEEN :DTINI AND :DTFIM
        AND RETENPORTO_U.CONFERIDO = 'S'
        AND (
            'X' IN (:UF)
            OR (CASE WHEN TRADING = 'S' THEN 'TR' ELSE UF.UF END) IN (:UF)
        )
        AND U_AGRPRODGR.U_AGRPRODGR_ID = :ITEM

),

BASE AS (
    SELECT
    UF,
    UFNOME,
    CIDENTREGA,
    ITEM,
    SUM(QTDCTR_C) AS QTDCTR_C,
    SUM(QTDCTR_C_SC) AS QTDCTR_C_SC,
    SUM(VENDIDO) AS VENDIDO,
    SUM(VENDIDO_SC) AS VENDIDO_SC,
    SUM(QTD_AFIXAR) AS QTD_AFIXAR,
    SUM(AFIXAR_SC) AS AFIXAR_SC,
    SUM(PESORETENCAO)PESORETENCAO,
    SUM(PESORETENCAO_SC)PESORETENCAO_SC,
    SUM(DESCARREGADO) AS DESCARREGADO,
    SUM(DESCARREGADO_SC) AS DESCARREGADO_SC,
    SUM(TRANSITO) AS TRANSITO,
    SUM(TRANSITO_SC) AS TRANSITO_SC,
    SUM(SALDOTOTAL) AS SALDOTOTAL
    FROM(
    
    SELECT
    CONTRATOS.UF,
    CONTRATOS.UFNOME,
    CONTRATOS.CIDENTREGA,
    CONTRATOS.ITEM,
    QTDCTR_C,
    ARREDONDAR(DIVIDE(CONTRATOS.QTDCTR_C,60),2) AS QTDCTR_C_SC,
    CONTRATOS.QTDCTR AS VENDIDO,
    ARREDONDAR(DIVIDE(CONTRATOS.QTDCTR,60),2) AS VENDIDO_SC,
    QTD_AFIXAR,
    ARREDONDAR(DIVIDE(CONTRATOS.QTD_AFIXAR,60),2) AS AFIXAR_SC,
    0 AS PESORETENCAO,
    0 AS PESORETENCAO_SC,
    0 DESCARREGADO,
    0 DESCARREGADO_SC,
    0 TRANSITO,
    0 TRANSITO_SC,
      0 AS SALDOTOTAL
    FROM CONTRATOS
        
    UNION ALL
    
    SELECT
    NOTAS.UF,
    NOTAS.UFNOME,
    NOTAS.CIDENTREGA,
    NOTAS.ITEM,
    0 AS QTDCTR_C,
    0 AS QTDCTR_C_SC,
    0 VENDIDO,
    0 VENDIDO_SC,
    0 AS QTD_AFIXAR,
    0 AS AFIXAR_SC,
    0 AS PESORETENCAO,
    0 AS PESORETENCAO_SC,
    0 DESCARREGADO,
    0 AS DESCARREGADO_SC,
    0 TRANSITO,
    0 AS TRANSITO_SC,
    SALDOTOTAL
    FROM NOTAS
    
    UNION ALL
    
    SELECT
    RETENCAO.UF,
    RETENCAO.UFNOME,
    RETENCAO.CIDENTREGA,
    RETENCAO.ITEM,
    0 AS QTDCTR_C,
    0 AS QTDCTR_C_SC,
    0 AS VENDIDO,
    0 AS VENDIDO_SC,
    0 QTD_AFIXAR,
    0 AFIXAR_SC,
    PESORETENCAO,
    PESORETENCAO_SC,
    0 DESCARREGADO,
    0 DESCARREGADO_SC,
    0 TRANSITO,
    0 TRANSITO_SC,
    0 AS SALDOTOTAL
    FROM RETENCAO
    
    )DADOS
    GROUP BY
    UF,
    UFNOME,
    CIDENTREGA,
    ITEM
)

SELECT * FROM (
    SELECT
    BASE.*,
    VENDIDO - SALDOTOTAL + QTD_AFIXAR AS A_EMBARCAR,
    VENDIDO_SC - ARREDONDAR(DIVIDE(SALDOTOTAL,60),2) + AFIXAR_SC AS A_EMBARCAR_SC,
    VENDIDO - SALDOTOTAL AS A_PERFORMAR,
    VENDIDO_SC - ARREDONDAR(DIVIDE(SALDOTOTAL,60),2) AS A_PERFORMAR_SC
    FROM BASE
) RESULTADO
WHERE
	VENDIDO > 0
   OR   A_EMBARCAR > 0
   OR A_EMBARCAR_SC > 0
   OR A_PERFORMAR > 0
   OR A_PERFORMAR_SC > 0
   OR  QTD_AFIXAR > 0