SELECT  ITEMAGRO.DESCRICAO AS ITEM,
        NFCFG.NOTACONF||'-'||NFCFG.DESCRICAO AS OPERACAO,
        LOCALEST.ESTAB||' - '||LOCALEST.DESCRICAO AS LOCALSAIDA,
        NFBX.LOCAL AS LOCALENTRADA,    
        NFITEM.QUANTIDADE AS QTDSAIDA,
        COALESCE(NFBX.QTD , 0) AS QTDENTRADA,
        NFITEM.QUANTIDADE - COALESCE(NFBX.QTD , 0) AS DIFERENCA,
        NFITEM.ESTAB,
        NFITEM.SEQNOTA,
        NFITEM.SEQNOTAITEM            
FROM NFCAB
INNER JOIN NFCFG
  ON NFCAB.NOTACONF = NFCFG.NOTACONF
INNER JOIN NFITEM
  ON NFCAB.ESTAB = NFITEM.ESTAB 
  AND NFCAB.SEQNOTA = NFITEM.SEQNOTA
INNER JOIN LOCALEST
  ON NFITEM.ESTAB = LOCALEST.ESTAB
  AND NFITEM.LOCAL = LOCALEST.LOCAL
INNER JOIN ITEMAGRO
  ON NFITEM.ITEM = ITEMAGRO.ITEM
LEFT JOIN ITEMGRUPO
  ON ITEMAGRO.GRUPO = ITEMGRUPO.GRUPO
LEFT JOIN ITEMMARCA
  ON ITEMAGRO.MARCA = ITEMMARCA.MARCA 
LEFT JOIN ( SELECT  NFITEMAPARTIRDE.ESTABORIGEM,
                    NFITEMAPARTIRDE.SEQNOTAORIGEM,
                    NFITEMAPARTIRDE.SEQNOTAITEMORIGEM,
                    LOCALEST.ESTAB||' - '||LOCALEST.DESCRICAO AS LOCAL,
                    SUM(NFITEMAPARTIRDE.QUANTIDADE) AS QTD
            FROM NFITEMAPARTIRDE
            INNER JOIN NFITEM
              ON NFITEMAPARTIRDE.ESTAB = NFITEM.ESTAB
              AND NFITEMAPARTIRDE.SEQNOTA = NFITEM.SEQNOTA
              AND NFITEMAPARTIRDE.SEQNOTAITEM = NFITEM.SEQNOTAITEM
            INNER JOIN LOCALEST
              ON NFITEM.ESTAB = LOCALEST.ESTAB
              AND NFITEM.LOCAL = LOCALEST.LOCAL
            GROUP BY NFITEMAPARTIRDE.ESTABORIGEM,
                    NFITEMAPARTIRDE.SEQNOTAORIGEM,
                    NFITEMAPARTIRDE.SEQNOTAITEMORIGEM,
                    LOCALEST.ESTAB,
                    LOCALEST.DESCRICAO)NFBX
    ON NFITEM.ESTAB = NFBX.ESTABORIGEM
    AND NFITEM.SEQNOTA = NFBX.SEQNOTAORIGEM
    AND NFITEM.SEQNOTAITEM = NFBX.SEQNOTAITEMORIGEM                   
WHERE NFCFG.ENTRADASAIDA = 'S'
  <#if ESTABORIGEM?has_content && ESTABDESTINO?has_content>
    AND NFCAB.ESTAB IN ( :ESTABORIGEM, :ESTABDESTINO)
  <#elseif ESTABORIGEM?has_content>
    AND NFCAB.ESTAB IN ( :ESTABORIGEM )
  <#elseif ESTABDESTINO?has_content>
    AND NFCAB.ESTAB IN ( :ESTABDESTINO )
  </#if>
  <#if ITEM?has_content>
    AND ITEMAGRO.ITEM IN ( :ITEM)
  </#if>
  <#if GRUPO?has_content>
    AND ITEMAGRO.GRUPO IN ( :GRUPO )
  </#if> 
  <#if MARCA?has_content>
    AND ITEMAGRO.MARCA IN ( :MARCA )
  </#if>  
  <#if GRUPOCONTABIL?has_content>
    AND ITEMGRUPO.GRUPOCONTABIL IN ( :GRUPOCONTABIL )
  </#if>