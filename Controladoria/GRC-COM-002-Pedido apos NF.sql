WITH BASE AS (
    SELECT DISTINCT
    PED.ESTAB,
    PED.SERIE,
    PED.NUMERO,
    PED.ESTABNOTA,
    PED.SEQNOTA,
    PEDCAB.DTEMISSAO AS DTPED,
    NFCAB.DTEMISSAO AS DTNF,
    CONTAMOV.NOME AS CLIENTE,
    CENCUSCE.CENTROCUS||'-'||CENCUSCE.DESCRICAO AS CC
    FROM PEDITEMNFITEM PED
    INNER JOIN NFITEM ON
        NFITEM.ESTAB = PED.ESTABNOTA
        AND NFITEM.SEQNOTA = PED.SEQNOTA
        AND NFITEM.SEQNOTAITEM = PED.SEQNOTAITEM
    INNER JOIN NFCAB ON
        NFCAB.ESTAB = NFITEM.ESTAB
        AND NFCAB.SEQNOTA = NFITEM.SEQNOTA
    INNER JOIN CONTAMOV ON CONTAMOV.NUMEROCM = NFCAB.NUMEROCM
    INNER JOIN PEDITEM ON
        PEDITEM.ESTAB = PED.ESTAB
        AND PEDITEM.SERIE = PED.SERIE
        AND PEDITEM.SEQPEDITE = PED.SEQPEDITE
        AND PEDITEM.NUMERO = PED.NUMERO
    INNER JOIN PEDCAB ON
        PEDCAB.ESTAB = PEDITEM.ESTAB
        AND PEDCAB.SERIE = PEDITEM.SERIE
        AND PEDCAB.NUMERO = PEDITEM.NUMERO
    LEFT JOIN CENCUSCE ON
        CENCUSCE.CENCUSCOD = NFCAB.CENCUSCOD
        AND CENCUSCE.CENTROCUS = NFCAB.CENTROCUS
    WHERE
    PEDCAB.STATUS <> 'C'
    AND NFCAB.STATUS <> 'C'
    AND PEDCAB.DTEMISSAO > NFCAB.DTEMISSAO
    AND NFCAB.DTEMISSAO >= '01/01/2026'
)
SELECT
*
FROM BASE