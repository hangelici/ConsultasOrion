--- R08_CAIXA_LOJA
SELECT
FILIAL.ESTAB AS COD_LOJA,
FILIAL.REDUZIDO AS NOME_LOJA,
PDUPREC.DUPREC AS ID_RECEBIMENTO,
DADOS.DTLANCA AS DATA_HORA_RECEBIMENTO,
PDUPREC.USERID AS USUARIO,
PDUPREC.CLIENTE AS COD_CLIENTE,
CONTAMOV.NOME AS NOME_CLIENTE,
NVL(ENDERECO.CNPJF,CONTAMOV.CNPJF) AS CPF_CNPJ_CLIENTE,
PDUPREC.QUITADA AS DOC_QUITADO,
DADOS.TIPO AS MEIO_PAGAMENTO,
SUM(DADOS.VALOR) AS VALOR,
'N' AS ESTORNADO,
NULL AS DATA_HORA_ESTORNO,
NULL AS USUARIO_ESTORNO
FROM(
SELECT EMPRESA,DUPREC,DTLANCA,VALOR, 'DINHEIRO' AS TIPO FROM PRDUPRED WHERE DTLANCA BETWEEN :DTINI AND :DTFIM
UNION ALL
SELECT EMPRESA,DUPREC,DTLANCA,VLRCHEQREC AS VALOR, 'CHEQUE' AS TIPO FROM PRDURECH WHERE DTLANCA BETWEEN :DTINI AND :DTFIM
UNION ALL
SELECT PRDUREDUP.EMPRESA,PRDUREDUP.DUPREC,PRDUPREC.DTRECBTO,PRDUREDUP.VALOR, 'DPL' AS TIPO FROM PRDUREDUP 
INNER JOIN PRDUPREC ON (PRDUREDUP.EMPRESA = PRDUPREC.EMPRESA)
                                            AND (PRDUREDUP.DUPREC = PRDUPREC.DUPREC)
                                            AND (PRDUREDUP.SEQRECBTO = PRDUPREC.SEQRECBTO)
WHERE DTRECBTO BETWEEN :DTINI AND :DTFIM
UNION ALL
SELECT PRDURECAR.EMPRESA,PRDURECAR.DUPREC,PRDUPREC.DTRECBTO,PRDURECAR.VALOR, 'CARTAO' AS TIPO FROM PRDURECAR 
INNER JOIN PRDUPREC ON (PRDURECAR.EMPRESA = PRDUPREC.EMPRESA)
                                             AND (PRDURECAR.DUPREC = PRDUPREC.DUPREC)
                                             AND (PRDURECAR.SEQRECBTO = PRDUPREC.SEQRECBTO)
WHERE DTRECBTO BETWEEN :DTINI AND :DTFIM
UNION ALL
SELECT PRDUREOUT.EMPRESA,PRDUREOUT.DUPREC,DTRECBTO,PRDUREOUT.VALOR, 'OUTROS' AS TIPO FROM PRDUREOUT 
INNER JOIN PRDUPREC ON (PRDUREOUT.EMPRESA = PRDUPREC.EMPRESA)
                                             AND (PRDUREOUT.DUPREC = PRDUPREC.DUPREC)
                                             AND (PRDUREOUT.SEQRECBTO = PRDUPREC.SEQRECBTO)
WHERE DTRECBTO BETWEEN :DTINI AND :DTFIM
UNION ALL
SELECT PRDURECM.EMPRESA,PRDURECM.DUPREC,DTRECBTO,PRDURECM.VALOR, 'CONTAMOV' AS TIPO FROM PRDURECM 
INNER JOIN PRDUPREC ON (PRDURECM.EMPRESA = PRDUPREC.EMPRESA)
                                             AND (PRDURECM.DUPREC = PRDUPREC.DUPREC)
                                             AND (PRDURECM.SEQRECBTO = PRDUPREC.SEQRECBTO)
WHERE TROCO = 'N' AND DTRECBTO BETWEEN :DTINI AND :DTFIM
) DADOS
INNER JOIN PDUPREC ON
    PDUPREC.EMPRESA = DADOS.EMPRESA
    AND PDUPREC.DUPREC = DADOS.DUPREC
INNER JOIN FILIAL ON FILIAL.ESTAB = PDUPREC.EMPRESA
INNER JOIN CONTAMOV ON CONTAMOV.NUMEROCM = PDUPREC.CLIENTE
LEFT JOIN ENDERECO ON
    ENDERECO.NUMEROCM  = PDUPREC.CLIENTE
    AND ENDERECO.SEQENDERECO = PDUPREC.SEQENDERECO

GROUP by
FILIAL.ESTAB,
FILIAL.REDUZIDO,
PDUPREC.DUPREC,
DADOS.DTLANCA,
PDUPREC.USERID,
PDUPREC.CLIENTE,
CONTAMOV.NOME,
ENDERECO.CNPJF,
CONTAMOV.CNPJF,
PDUPREC.QUITADA,
DADOS.TIPO