--- R08_CAIXA_LOJA
WITH
PARAM AS (
    SELECT TO_DATE(:DTINI, 'DD/MM/YYYY') AS DTINI,
           TO_DATE(:DTFIM, 'DD/MM/YYYY') AS DTFIM
    FROM DUAL
),
MEIOS_REC AS (
    SELECT EMPRESA, DUPREC, SEQRECBTO, VALOR, 'DPL'      AS TIPO FROM PRDUREDUP WHERE (0 IN (:ESTAB) OR PRDUREDUP.EMPRESA IN (:ESTAB))
    UNION ALL
    SELECT EMPRESA, DUPREC, SEQRECBTO, VALOR, 'CARTAO'   AS TIPO FROM PRDURECAR WHERE (0 IN (:ESTAB) OR PRDURECAR.EMPRESA IN (:ESTAB))
    UNION ALL
    SELECT EMPRESA, DUPREC, SEQRECBTO, VALOR, 'OUTROS'   AS TIPO FROM PRDUREOUT WHERE (0 IN (:ESTAB) OR PRDUREOUT.EMPRESA IN (:ESTAB))
    UNION ALL
    SELECT EMPRESA, DUPREC, SEQRECBTO, VALOR, 'CONTAMOV' AS TIPO FROM PRDURECM WHERE TROCO = 'N' AND (0 IN (:ESTAB) OR PRDURECM.EMPRESA IN (:ESTAB))
),
DADOS AS (
    SELECT EMPRESA, DUPREC, DTLANCA, TIPO, SUM(VALOR) AS VALOR
    FROM (
        SELECT D.EMPRESA, D.DUPREC, D.DTLANCA, D.VALOR, 'DINHEIRO' AS TIPO
        FROM PRDUPRED D, PARAM P, U_TEMPRESA
        WHERE D.DTLANCA BETWEEN P.DTINI AND P.DTFIM
        AND U_TEMPRESA.ESTAB = D.EMPRESA AND U_TEMPRESA.INSUMOS = 'S'
        UNION ALL
        SELECT C.EMPRESA, C.DUPREC, C.DTLANCA, C.VLRCHEQREC, 'CHEQUE'
        FROM PRDURECH C, PARAM P, U_TEMPRESA
        WHERE C.DTLANCA BETWEEN P.DTINI AND P.DTFIM
        AND U_TEMPRESA.ESTAB = C.EMPRESA AND U_TEMPRESA.INSUMOS = 'S'
        UNION ALL
        SELECT R.EMPRESA, R.DUPREC, R.DTRECBTO, M.VALOR, M.TIPO
        FROM PRDUPREC R
        INNER JOIN U_TEMPRESA ON U_TEMPRESA.ESTAB = R.EMPRESA
        INNER JOIN MEIOS_REC M
                ON M.EMPRESA   = R.EMPRESA
               AND M.DUPREC    = R.DUPREC
               AND M.SEQRECBTO = R.SEQRECBTO
        CROSS JOIN PARAM P
        WHERE R.DTRECBTO BETWEEN P.DTINI AND P.DTFIM AND R.TIPOREC = 'R'
        AND (0 IN (:ESTAB) OR R.EMPRESA IN (:ESTAB))
    )
    GROUP BY EMPRESA, DUPREC, DTLANCA, TIPO
)
SELECT
    FILIAL.ESTAB                         AS COD_LOJA,
    FILIAL.REDUZIDO                      AS NOME_LOJA,
    PDUPREC.DUPREC                       AS ID_RECEBIMENTO,
    DADOS.DTLANCA                        AS DATA_HORA_RECEBIMENTO,
    PDUPREC.USERID                       AS USUARIO,
    PDUPREC.CLIENTE                      AS COD_CLIENTE,
    CONTAMOV.NOME                        AS NOME_CLIENTE,
    NVL(ENDERECO.CNPJF, CONTAMOV.CNPJF)  AS CPF_CNPJ_CLIENTE,
    PDUPREC.QUITADA                      AS DOC_QUITADO,
    DADOS.TIPO                           AS MEIO_PAGAMENTO,
    DADOS.VALOR                          AS VALOR,
    'N'                                  AS ESTORNADO,
    NULL                                 AS DATA_HORA_ESTORNO,
    NULL                                 AS USUARIO_ESTORNO
FROM DADOS
INNER JOIN PDUPREC
        ON PDUPREC.EMPRESA = DADOS.EMPRESA
       AND PDUPREC.DUPREC  = DADOS.DUPREC
INNER JOIN FILIAL   ON FILIAL.ESTAB      = PDUPREC.EMPRESA
INNER JOIN CONTAMOV ON CONTAMOV.NUMEROCM = PDUPREC.CLIENTE
LEFT  JOIN ENDERECO ON ENDERECO.NUMEROCM    = PDUPREC.CLIENTE
                   AND ENDERECO.SEQENDERECO = PDUPREC.SEQENDERECO
