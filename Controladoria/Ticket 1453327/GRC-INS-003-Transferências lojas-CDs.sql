WITH BASE AS (
    SELECT  /*+ MATERIALIZE */
    PEDCAB.ESTAB,
    PEDCAB.SERIE,
    PEDCAB.NUMERO,
    PEDCAB.STATUS,
    PEDCAB.PESSOA,
    PEDCFG.PEDIDOCONF||'-'||PEDCFG.DESCRICAO AS CONFIG
    FROM PEDCAB
    INNER JOIN PEDCFG on
        PEDCFG.PEDIDOCONF = PEDCAB.PEDIDOCONF
    INNER JOIN CONTAMOV ON CONTAMOV.NUMEROCM = PEDCAB.PESSOA
    INNER JOIN FILIAL ON FILIAL.CNPJ = CONTAMOV.CNPJF
    WHERE PEDCAB.SERIE IN ('PT','PTE')
    AND PEDCAB.STATUS <> 'C'
),
BAIXAS AS (
    SELECT
    PED.ESTAB,
    PED.SERIE,
    PED.NUMERO,
    PED.SEQPEDITE,
    SUM(PED.QUANTIDADE) AS QTD
    FROM PEDITEMNFITEM PED
    INNER JOIN BASE ON
        BASE.ESTAB = PED.ESTAB
        AND BASE.SERIE = PED.SERIE
        AND BASE.NUMERO = PED.NUMERO

    GROUP BY PED.ESTAB,
    PED.SERIE,
    PED.NUMERO,
    PED.SEQPEDITE
)
SELECT
BASE.ESTAB,
BASE.NUMERO,
BASE.SERIE,
BASE.CONFIG,
BASE.PESSOA,
BASE.STATUS,
PEDITEM.DTEMISSAO,
PEDITEM.QUANTIDADE,
PEDITEM.CANCELADO,
BAIXAS.QTD as BAIXAS,
(PEDITEM.QUANTIDADE - NVL(PEDITEM.CANCELADO,0) - NVL(BAIXAS.QTD,0))  AS SALDO,
CASE
    WHEN BASE.STATUS = 'B' AND BAIXAS.QTD IS NULL THEN 'Baixado Sem Nota'
    WHEN BASE.STATUS = 'B' AND (PEDITEM.QUANTIDADE - NVL(PEDITEM.CANCELADO,0) - NVL(BAIXAS.QTD,0))   > 0 THEN 'Baixado e Aberto'
    WHEN BASE.STATUS <> 'B' AND BAIXAS.QTD IS NULL THEN 'Aberto e Sem Nota'
    WHEN BASE.STATUS <> 'B' AND BAIXAS.QTD IS NOT NULL THEN 'Aberto e Baixa Parcial'
end STATUS_BAIXA
FROM BASE
INNER JOIN PEDITEM on
    PEDITEM.ESTAB = BASE.ESTAB
    AND PEDITEM.SERIE = BASE.SERIE
    AND PEDITEM.NUMERO = BASE.NUMERO

LEFT JOIN BAIXAS on
    PEDITEM.ESTAB = BAIXAS.ESTAB
    AND PEDITEM.SERIE = BAIXAS.SERIE
    AND PEDITEM.NUMERO = BAIXAS.NUMERO
    AND PEDITEM.SEQPEDITE = BAIXAS.SEQPEDITE

WHERE
ARREDONDAR((PEDITEM.QUANTIDADE - NVL(PEDITEM.CANCELADO,0) - NVL(BAIXAS.QTD,0)),0)  <> 0 
AND (PEDITEM.QUANTIDADE <> NVL(PEDITEM.CANCELADO,0))
AND PEDITEM.DTEMISSAO > '01/01/2025'